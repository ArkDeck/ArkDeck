#!/usr/bin/env python3
"""Generate the exact protocol vocabulary; --check is a read-only drift check.

`--derive-method-schemas <frames>` additionally rewrites the per-method typed
contracts under spec/control/methods/ from control frames a debug daemon
recorded (ARKDECK_CONTROL_FRAME_LOG), and selects the committed frame corpus.
"""

import argparse
import hashlib
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
repository_root = root.parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
parser.add_argument(
    "--derive-method-schemas", metavar="FRAMES",
    help="derive spec/control/methods/<method>.json from control frames recorded by "
    "ARKDECK_CONTROL_FRAME_LOG (a directory of *.jsonl files or one file), and "
    "select the committed frame corpus under Tests/ArkDeckContractTests/Fixtures/ControlFrames")
args = parser.parse_args()
contract = json.loads((root / "Contracts/control-protocol.json").read_text())

def literal(value):
    return json.dumps(value, ensure_ascii=True)

lines = [
    "// Generated by Scripts/generate-control-contract.py. Do not edit.",
    "// Source: Contracts/control-protocol.json",
    "",
    "package enum ArkDeckControlProtocol {",
]
identity = hashlib.sha256(json.dumps(contract, sort_keys=True, separators=(",", ":")).encode()).hexdigest()
if contract["currentVersion"] != "1.0.0" or contract["methods"] != sorted(set(contract["methods"])):
    raise SystemExit("control contract requires one exact version and unique sorted methods")
for field in ["currentVersion", "maximumRequestFrameBytes", "maximumResponseFrameBytes"]:
    lines.append(f"  package static let {field} = {literal(contract[field])}")
lines.append(f"  package static let contractIdentity = {literal(identity)}")
lines.append("  package static let methods: Set<String> = [")
lines.extend(f"    {literal(method)}," for method in contract["methods"])
lines.append("  ]")
lines.extend(["}", ""])
expected = "\n".join(lines)
destination = root / "Sources/ArkDeckCore/ControlProtocolGenerated.swift"
if args.check:
    if not destination.exists() or destination.read_text() != expected:
        raise SystemExit("control protocol generated source drifted; run generate-control-contract.py")
else:
    destination.write_text(expected)


