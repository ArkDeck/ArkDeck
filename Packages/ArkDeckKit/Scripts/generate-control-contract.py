# Members keyed by caller data — operation input names, Artifact fact names,
# provenance keys — rather than records with a fixed member set. Each is
# published as a map, `{"type": "object", "additionalProperties": <schema of
# every sampled value>}` without `properties`, so a key no frame recorded is
# accepted with a value of a recorded type. Every other object stays closed to
# the members the daemon emitted. A path names the `$defs` part and then object
# members; `[]` steps into array items, `*` into a map's values. Reviewed
# against the Swift type that encodes each member: list only dictionaries.
# `operation.describe`'s example inputs stay closed: their keys are the
# Catalog's own input names, fixed by the build, and arkdeck-control validates
# the description of every Catalog operation against the published schema.
MAP_VALUED_MEMBERS = {
    # RuntimeAgentExecutionRequest.inputs: [String: JSONValue]
    "agent.run": ["request.inputs"],
    # RuntimeCapability.inputConstraints: [String: RuntimeCapabilityInputConstraint],
    # .exactInputs: [String: JSONValue]?, .exactArtifactFacts: [String: String]?
    "capability.inspect": [
        "result.capability.exactArtifactFacts", "result.capability.exactInputs",
        "result.capability.inputConstraints",
    ],
    # The Job evidence document's `parameters`: [String: JSONValue]
    "job.evidence": ["result.parameters"],
    # RuntimePlanOnlyPreview.inputs: [String: JSONValue]
    "job.plan": ["result.inputs"],
    "job.result": ["result.evidence.parameters"],
    # RuntimeOperationRequest.inputs: [String: JSONValue],
    # RuntimeClientContext.provenance: [String: String]?
    "job.show": ["result.request.clientContext.provenance", "result.request.inputs"],
}
# Room for every committed shape of a method plus the shapes a new oracle
# adds: the selection keeps the first N shapes in sort order, so a method at
# the bound silently loses a committed shape (job.result held 23).
MAXIMUM_SIGNATURES_PER_METHOD = 32
MAXIMUM_SAMPLE_BYTES = 65536


def json_type(value):
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "boolean"
    if isinstance(value, int):
        return "integer"
    if isinstance(value, float):
        return "number"
    if isinstance(value, str):
        return "string"
    if isinstance(value, list):
        return "array"
    return "object"


def signature(value):
    """A structural fingerprint: key set with member types, recursively."""
    kind = json_type(value)
    if kind == "object":
        return "{" + ",".join(f"{key}:{signature(value[key])}" for key in sorted(value)) + "}"
    if kind == "array":
        return "[" + "|".join(sorted({signature(item) for item in value})) + "]"
    return kind


def values_at(value, path):
    """Every value at `path` (`infer`'s spelling, without its root) below `value`."""
    if not path:
        return [value]
    head, _, rest = path.partition(".")
    step = head[:-2] if head.endswith("[]") else head
    if not isinstance(value, dict) or step not in value:
        return []
    member = value[step]
    if head.endswith("[]"):
        return [found for item in (member if isinstance(member, list) else []) for found in values_at(item, rest)]
    return values_at(member, rest)


# The samples SHARED_MEMBERS lends the method being derived, by path.
SHARED_SAMPLES = {}


def infer(values, closed, path="", maps=None):
    """The narrowest schema in the validator's vocabulary that admits every sample.

    `path` names where the samples sit, as MAP_VALUED_MEMBERS spells it. An
    object at a path in `maps` is published as a map, and the path is marked
    as reached. A path in SHARED_SAMPLES also admits the samples recorded for
    the same member in another method.
    """
    maps = {} if maps is None else maps
    if path in SHARED_SAMPLES:
        values = list(values) + [value for value in SHARED_SAMPLES[path] if value not in values]
    kinds = sorted({json_type(value) for value in values})
    if kinds == ["integer", "number"] or kinds == ["number"]:
        return {"type": "number"}
    if len(kinds) == 1 and kinds[0] not in ("object", "array"):
        return {"type": kinds[0]}
    branches = []
    for kind in kinds:
        members = [value for value in values if json_type(value) == kind]
        if kind == "object" and path in maps:
            maps[path] = True
            entries = [entry for member in members for entry in member.values()]
            # With only empty maps recorded, no value is published.
            branches.append({
                "type": "object",
                "additionalProperties": infer(entries, closed, path + ".*", maps) if entries else False,
            })
        elif kind == "object":
            keys = sorted({key for member in members for key in member})
            schema = {"type": "object"}
            if closed:
                schema["additionalProperties"] = False
            schema["properties"] = {
                key: infer([member[key] for member in members if key in member], closed, f"{path}.{key}", maps)
                for key in keys
            }
            required = [key for key in keys if all(key in member for member in members)]
            if required:
                schema["required"] = required
            branches.append(schema)
        elif kind == "array":
            items = [item for member in members for item in member]
            schema = {"type": "array"}
            if items:
                schema["items"] = infer(items, closed, path + "[]", maps)
            branches.append(schema)
        elif kind == "integer" and "number" in kinds:
            continue
        else:
            branches.append({"type": kind})
    if len(branches) == 1:
        return branches[0]
    scalar = [branch for branch in branches if set(branch) == {"type"}]
    structured = [branch for branch in branches if set(branch) != {"type"}]
    if not structured:
        return {"type": [branch["type"] for branch in scalar]}
    return {"anyOf": structured + ([{"type": [branch["type"] for branch in scalar]}] if scalar else [])}


def load_frames(source):
    path = Path(source)
    files = sorted(path.glob("*.jsonl")) if path.is_dir() else [path]
    frames = []
    skipped = 0
    for file in files:
        for line in file.read_text().splitlines():
            line = line.strip()
            if not line:
                continue
            try:
                frames.append((json.loads(line), line))
            except json.JSONDecodeError:
                # A test process killed mid-append leaves one torn tail line.
                skipped += 1
    if skipped:
        print(f"skipped {skipped} undecodable line(s)", file=sys.stderr)
    return frames


def derive_method_schemas(source):
    frames = load_frames(source)
    published = set(contract["methods"])
    unpublished = sorted(set(MAP_VALUED_MEMBERS) - published)
    if unpublished:
        raise SystemExit("MAP_VALUED_MEMBERS names unpublished methods: " + ", ".join(unpublished))
    current = contract["currentVersion"]
    by_method = {}
    for frame, line in frames:
        method = frame["method"]
        # The handler refuses every other version before dispatch, so a frame
        # carrying one could only come from a foreign recording.
        if method not in published or frame.get("protocolVersion") != current:
            continue
        by_method.setdefault(method, []).append((frame, line))
    missing = sorted(published - set(by_method))
    if missing:
        print("no recorded frames for: " + ", ".join(missing), file=sys.stderr)
    METHOD_SCHEMA_DIRECTORY.mkdir(parents=True, exist_ok=True)
    FRAME_CORPUS_DIRECTORY.mkdir(parents=True, exist_ok=True)
    for stale in list(METHOD_SCHEMA_DIRECTORY.glob("*.json")) + list(FRAME_CORPUS_DIRECTORY.glob("*.jsonl")):
        if stale.stem not in published:
            stale.unlink()
    for method in sorted(by_method):
        samples = by_method[method]
        params = [frame.get("params", {}) for frame, _ in samples]
        results = [frame["result"] for frame, _ in samples if frame["ok"] and "result" in frame]
        errors = [frame["error"] for frame, _ in samples if not frame["ok"]]
        details = [error["details"] for error in errors if "details" in error]
        codes = sorted({error["code"] for error in errors} | set(GENERIC_ERROR_CODES)
                       | (set(HISTORY_OWNER_ERROR_CODES) if method in {
                           "history.filter.list", "history.filter.save", "history.filter.delete"
                       } else set())
                       | (set(STORAGE_OWNER_ERROR_CODES) if method in {
                           "runtime.storage.status", "runtime.storage.policy", "runtime.storage.root"
                       } else set())
                       | (set(SESSION_OWNER_ERROR_CODES) if method in {
                           "session.list", "session.show", "session.pin", "session.unpin",
                           "session.cleanup.preview", "session.export.preview", "session.export.apply"
                       } else set())
                       | (set(BUNDLE_LIST_OWNER_ERROR_CODES) if method == "runtime.bundle.list" else set())
                       | (set(BUNDLE_RETIREMENT_OWNER_ERROR_CODES) if method == "runtime.bundle.remove" else set())
                       | (set(TOOL_RETIREMENT_OWNER_ERROR_CODES) if method == "runtime.tool.remove" else set())
                       | (set(TOOL_LIST_OWNER_ERROR_CODES) if method == "runtime.tool.list" else set())
                       | (set(TOOL_INSPECT_OWNER_ERROR_CODES) if method == "runtime.tool.inspect" else set())
                       | (set(AGENT_RESUME_OWNER_ERROR_CODES) if method in {"agent.resume", "human-action.resume"} else set())
                       | (set(TRACE_CACHE_PURGE_OWNER_ERROR_CODES) if method == "trace.cache.purge" else set())
                       | (set(TARGET_DISPLAY_NAME_OWNER_ERROR_CODES) if method in {
                           "target.display-name.set", "target.display-name.clear"
                       } else set())
                       | (set(IMPORT_OWNER_ERROR_CODES) if method.startswith("artifact.import.") else set())
                       | (set(AGENT_RUN_OWNER_ERROR_CODES) if method == "agent.run" else set())
                       | (set(ARTIFACT_EXPORT_OWNER_ERROR_CODES) if method == "artifact.export" else set()))
        SHARED_SAMPLES.clear()
        for (source, source_path), targets in SHARED_MEMBERS.items():
            for target, target_path in targets:
                if target != method:
                    continue
                root, _, member = source_path.partition(".")
                frames = [frame for frame, _ in by_method.get(source, [])]
                answers = [frame.get(root) for frame in frames if root in frame]
                if not answers:
                    raise SystemExit(
                        f"SHARED_MEMBERS: {target} {target_path} needs {source}'s recorded frames"
                    )
                SHARED_SAMPLES[target_path] = [
                    value for answer in answers for value in values_at(answer, member)
                ]
        maps = dict.fromkeys(MAP_VALUED_MEMBERS.get(method, []), False)
        schema = {
            "$schema": "https://json-schema.org/draft/2020-12/schema",
            "$id": f"https://arkdeck.dev/schemas/control/methods/{method}.json",
            "title": f"arkdeck.control.method/{method}",
            "description": (
                f"Typed contract of the control-plane method `{method}` on the single current "
                "protocol: the request parameters a caller may send, the result the Runtime "
                "answers with, and the structured error details it attaches to a refusal. "
                "Derived from frames recorded by a contract-test run; the committed corpus under "
                "Tests/ArkDeckContractTests/Fixtures/ControlFrames is validated against it."),
            "x-arkdeck-method": method,
            "x-arkdeck-protocolVersion": current,
            "x-arkdeck-contractIdentity": identity,
            "x-arkdeck-sampleCounts": {
                "request": len(params), "result": len(results), "error": len(errors),
            },
            "$defs": {
                "request": infer(params, closed=True, path="request", maps=maps),
                "result": infer(results, closed=True, path="result", maps=maps) if results else {
                    "description": (
                        "no successful frame was recorded, so the result shape is not published "
                        "yet; a contract test that exercises the success path through the control "
                        "plane publishes it"),
                    "x-arkdeck-unpublished": True,
                },
                "errorCode": {"enum": codes},
                "errorDetails": infer(details, closed=True, path="errorDetails", maps=maps) if details else {"type": "object", "additionalProperties": False, "properties": {}},
            },
        }
        if method == "runtime.bundle.register" and results:
            # Registration returns the same frozen Bundle projection, including
            # previously acquired references on idempotent registration. Reuse
            # actual inspection results without inventing registration frames.
            inspection = load_frames(FRAME_CORPUS_DIRECTORY / "runtime.bundle.inspect.jsonl")
            projections = [frame["result"] for frame, _ in inspection if frame["ok"]]
            schema["$defs"]["result"] = infer(projections + results, closed=True, path="result", maps=maps)
        if method in {"runtime.tool.list", "runtime.tool.remove"} and results:
            # Both leaves return the existing Tool projection. Preserve its
            # native optional trust/dependency/selection fields from actual
            # inspection recordings, including shapes outside this phase's
            # permitted host fixtures. Never manufacture a producer frame.
            inspection = load_frames(FRAME_CORPUS_DIRECTORY / "runtime.tool.inspect.jsonl")
            projections = [frame["result"] for frame, _ in inspection if frame["ok"]]
            if method == "runtime.tool.list":
                projections += [row for result in results for row in result["items"]]
                schema["$defs"]["result"]["properties"]["items"]["items"] = infer(
                    projections, closed=True, path="result.items[]", maps=maps)
            else:
                schema["$defs"]["result"] = infer(projections + results, closed=True, path="result", maps=maps)
        unreached = sorted(path for path, reached in maps.items() if not reached)
        if unreached:
            print(f"{method}: no recorded frame reaches the map-valued member(s) "
                  + ", ".join(unreached) + ", so they are not published", file=sys.stderr)
        (METHOD_SCHEMA_DIRECTORY / f"{method}.json").write_text(
            json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n")
        # The committed corpus: the smallest frame of every distinct request and
        # response shape, bounded per method, in a deterministic order.
        groups = {}
        for frame, line in samples:
            if len(line.encode()) > MAXIMUM_SAMPLE_BYTES:
                continue
            key = (signature(frame.get("params", {})), signature(frame.get("result", frame.get("error"))), frame["ok"])
            if key not in groups or len(line) < len(groups[key]):
                groups[key] = line
        selected = [groups[key] for key in sorted(groups)[:MAXIMUM_SIGNATURES_PER_METHOD]]
        # Refusals of one shape differ only in their code, so the selection can
        # keep one code of a shape and drop the frame of another. Keep the
        # smallest frame of every recorded code it dropped, so that a later
        # derivation over the committed corpus publishes the same codes.
        evidenced = {json.loads(line)["error"]["code"] for line in selected if not json.loads(line)["ok"]}
        dropped = {}
        for frame, line in samples:
            if frame["ok"] or len(line.encode()) > MAXIMUM_SAMPLE_BYTES:
                continue
            code = frame["error"]["code"]
            if code not in evidenced and (code not in dropped or len(line) < len(dropped[code])):
                dropped[code] = line
        selected += [dropped[code] for code in sorted(dropped)]
        (FRAME_CORPUS_DIRECTORY / f"{method}.jsonl").write_text("\n".join(selected) + "\n")
    print(f"derived {len(by_method)} method schemas from {len(frames)} frames; corpus written")


if args.derive_method_schemas:
    derive_method_schemas(args.derive_method_schemas)
