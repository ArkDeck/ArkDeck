  func testNextActionFixturesFollowTheirSchemaBranch() throws {
    let schema = try JSONValueBridge.value(
      from: Data(contentsOf: Self.contractsDirectory.appending(path: "cli-next-action.schema.json")))
    guard case .object(let schemaFields) = schema, case .object(let branches)? = schemaFields["$defs"]
    else { return XCTFail("next-action schema has no branches") }
    XCTAssertEqual(schemaFields["title"], .string(CLIMachineContracts.nextActionSchemaVersion))
    XCTAssertEqual(Set(branches.keys), ["wait", "humanAction", "reconcile", "cleanup", "readResult"])
    let directory = Self.fixturesDirectory.appending(path: "next-action")
    let files = try FileManager.default.contentsOfDirectory(atPath: directory.path).sorted()
    XCTAssertEqual(Set(files), Set(branches.keys.map { "\($0).json" } + ["null.json"]))
    for file in files {
      let document = try JSONValueBridge.value(from: Data(contentsOf: directory.appending(path: file)))
      if file == "null.json" {
        XCTAssertEqual(document, .null)
        continue
      }
      let kind = String(file.dropLast(".json".count))
      guard case .object(let branch)? = branches[kind],
        case .array(let required)? = branch["required"],
        case .object(let properties)? = branch["properties"],
        case .object(let fields) = document,
        case .object(let reasonCode)? = properties["reasonCode"]
      else { return XCTFail("\(file) or its branch is malformed"); }
      XCTAssertEqual(fields["kind"], .string(kind))
      let requiredKeys = Set(required.compactMap { value -> String? in
        if case .string(let text) = value { return text }
        return nil
      })
      XCTAssertTrue(requiredKeys.isSubset(of: Set(fields.keys)), "\(file) misses a required field")
      XCTAssertTrue(Set(fields.keys).isSubset(of: Set(properties.keys)), "\(file) carries a field outside its branch")
      if case .array(let codes)? = reasonCode["enum"] {
        XCTAssertTrue(codes.contains(fields["reasonCode"] ?? .null), "\(file) uses a reason code outside the vocabulary")
      }
    }
  }

