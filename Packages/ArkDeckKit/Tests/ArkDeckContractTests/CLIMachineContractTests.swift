  // MARK: Schemas accept the real output and reject counterexamples

  private func schema(_ name: String) throws -> JSONValue {
    try JSONValueBridge.value(
      from: Data(contentsOf: Self.contractsDirectory.appending(path: "\(name).schema.json")))
  }

  private func fixture(_ path: String) throws -> JSONValue {
    try JSONValueBridge.value(from: Data(contentsOf: Self.fixturesDirectory.appending(path: path)))
  }

  private func jsonlLine(_ path: String) throws -> JSONValue {
    let text = try String(contentsOf: Self.fixturesDirectory.appending(path: path), encoding: .utf8)
    return try JSONValueBridge.value(from: Data(text.split(separator: "\n")[0].utf8))
  }

  private func mutate(_ value: JSONValue, _ body: (inout [String: JSONValue]) -> Void) -> JSONValue {
    guard case .object(var fields) = value else { return value }
    body(&fields)
    return .object(fields)
  }

  func testResultSchemaAcceptsRenderedEnvelopesAndRejectsCounterexamples() throws {
