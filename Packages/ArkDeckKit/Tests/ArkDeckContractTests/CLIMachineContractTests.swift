          fields["error"] = self.mutate(fields["error"] ?? .null) { $0["code"] = .string("notARegisteredCode") }
        }, against: schema), "unregistered error code")
    XCTAssertFalse(
      JSONSchemaSubset.validate(
        mutate(success) { fields in
