  func testFeatureCoverageIsClosedAndDeclaresFullFunction() throws {
    let coverage = try CLIMachineContracts.FeatureCoverage.build()
    let features = Dictionary(uniqueKeysWithValues: coverage.entries.map { ($0.feature, $0) })
    XCTAssertEqual(features.count, coverage.entries.count, "feature ids must be unique")

    for method in CLIControlMethodRegistry.classifiedMethods {
      XCTAssertNotNil(features[method], "daemon method \(method) has no coverage entry")
    }
    XCTAssertEqual(features[ArkDeckControlProtocol.bootstrapMethod]?.classification, "internal")
    for descriptor in RuntimeOperationCatalog.operations {
      XCTAssertNotNil(features[descriptor.reference], "Catalog operation \(descriptor.reference) is uncovered")
    }
    for capability in AppProductCapabilityRegistry.capabilities {
      let entry = try XCTUnwrap(features[capability.id], "App capability \(capability.id) is uncovered")
      XCTAssertEqual(entry.classification, capability.classification.rawValue)
      XCTAssertEqual(entry.owner, capability.owner)
    }
    let referenced = Set(coverage.entries.flatMap(\.referencedLeaves))
    for (_, leaf) in CLICommandRegistry.allLeaves() {
      XCTAssertTrue(referenced.contains(leaf.canonicalCommand), "leaf \(leaf.canonicalCommand) is uncovered")
    }

    // Spot facts a reader of the table relies on.
    XCTAssertEqual(features["job.evidence"]?.classification, "direct")
    XCTAssertEqual(features["job.evidence"]?.targetCommand, "arkdeck job evidence --job <job-id>")
    XCTAssertEqual(features["job.evidence"]?.conformanceFixture, "argv/job.evidence.json")
    XCTAssertEqual(features["capability.draft"]?.classification, "refused")
    XCTAssertEqual(features["artifact.import.append"]?.classification, "internal")
    XCTAssertEqual(features["session.list"]?.classification, "local")
    XCTAssertEqual(features["runtime.hdc-status"]?.lifecycle, "legacy")
    XCTAssertEqual(features["agent.chat"]?.lifecycle, "removed")
    XCTAssertEqual(features["agent.chat"]?.classification, "refused")
    XCTAssertEqual(features["observe.device@1"]?.classification, "direct")
    XCTAssertEqual(features["observe.device@1"]?.targetCommand, "arkdeck target observe")
    XCTAssertEqual(features["app.settings.servers"]?.classification, "platformService")
    XCTAssertEqual(features["app.design.components"]?.classification, "presentation")

    let generic = coverage.entries.filter { $0.classification == "generic" }
    for entry in generic {
      XCTAssertTrue(entry.source.hasPrefix("catalog:"))
      XCTAssertEqual(
        entry.targetCommand,
        "arkdeck job submit --operation \(entry.feature) --inputs-file <path>")
    }
    XCTAssertTrue(
      coverage.entries.filter { $0.classification == "blocked" }.isEmpty,
      "§18 full function requires no blocked entry")
    guard case .object(let document) = coverage.document,
      case .object(let summary)? = document["summary"]
    else { return XCTFail("coverage document has no summary") }
    XCTAssertEqual(summary["fullFunction"], .bool(true))
    XCTAssertEqual(summary["entries"], .integer(Int64(coverage.entries.count)))
  }

