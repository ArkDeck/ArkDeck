/// The §14 machine-contract bundle is a projection of this build, and the
/// committed copy must be exactly that projection. These tests hold the
/// published files to the binary, replay the argv fixtures through the
/// parser, and check that the schemas pin the values the implementation
/// actually uses — so a registry change that forgets to regenerate the bundle,
/// or a bundle edited by hand, fails here rather than in a port.
final class CLIMachineContractTests: XCTestCase {
  private static let repositoryRoot: URL = {
    var url = URL(filePath: #filePath)
    for _ in 0..<5 { url.deleteLastPathComponent() }
    return url
  }()
  private static let contractsDirectory = repositoryRoot.appending(path: "openspec/contracts")
  private static let fixturesDirectory = repositoryRoot.appending(
    path: "Packages/ArkDeckKit/Tests/ArkDeckContractTests/Fixtures/CLI")
  private static let regenerate =
    "regenerate with `arkdeck maintainer contracts export --contracts-directory openspec/contracts "
    + "--fixtures-directory Packages/ArkDeckKit/Tests/ArkDeckContractTests/Fixtures/CLI`"

