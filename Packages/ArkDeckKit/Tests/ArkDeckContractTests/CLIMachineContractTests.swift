  // MARK: Argv fixtures

  func testCommittedArgvFixturesReplayThroughTheParser() throws {
    let argvDirectory = Self.fixturesDirectory.appending(path: "argv")
    let files = try FileManager.default.contentsOfDirectory(atPath: argvDirectory.path)
      .filter { $0.hasSuffix(".json") }.sorted()
    XCTAssertEqual(files.count, CLICommandRegistry.allLeaves().count, Self.regenerate)
    var replayed = 0
    for file in files {
      let data = try Data(contentsOf: argvDirectory.appending(path: file))
      let fixture = try JSONValueBridge.value(from: data)
      guard case .object(let fields) = fixture,
        case .string(let command)? = fields["command"],
        case .string(let kind)? = fields["kind"],
        case .array(let cases)? = fields["cases"]
      else { return XCTFail("\(file) is not an argv fixture") }
      XCTAssertEqual(fields["schemaVersion"], .string(CLIMachineContracts.argvFixtureSchemaVersion))
      XCTAssertEqual(file, "\(command).json")
      for entry in cases {
        guard case .object(let entryFields) = entry,
          case .string(let name)? = entryFields["name"],
          case .array(let argvValues)? = entryFields["argv"],
          let expected = entryFields["expected"]
        else { return XCTFail("\(file) has a malformed case") }
        let argv = argvValues.compactMap { value -> String? in
          if case .string(let text) = value { return text }
          return nil
        }
        let parsed = CLIArgumentParser.parse(argv)
        let actual = CLIMachineContracts.ArgvFixtures.outcome(parsed)
        XCTAssertEqual(
          try CLICanonicalJSON.canonicalString(actual),
          try CLICanonicalJSON.canonicalString(expected),
          "\(file) case \(name): \(argv); \(Self.regenerate)")
        replayed += 1
        guard name == "valid" else { continue }
        switch (kind, parsed) {
        case ("executable", .success(.dispatch(_, let leaf, _))):
          XCTAssertEqual(leaf.canonicalCommand, command)
        case ("executable", .success):
          break  // help/commands/completion answer without dispatching
        case ("tombstone", .failure(let error)):
          XCTAssertEqual(error.code, .commandRemoved, file)
        case ("refused", .failure(let error)):
          XCTAssertEqual(error.code.category, .usage, file)
        default:
          XCTFail("\(file): the valid case of a \(kind) leaf produced an unexpected outcome")
        }
      }
    }
    XCTAssertGreaterThan(replayed, files.count * 2)
  }

