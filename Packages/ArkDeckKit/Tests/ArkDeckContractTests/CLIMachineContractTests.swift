  func testJSONProductsParseAndYAMLProductsRoundTrip() throws {
    for product in try CLIMachineContracts.contractProducts() + CLIMachineContracts.fixtureProducts() {
      if product.relativePath.hasSuffix(".json") {
        XCTAssertNoThrow(
          try JSONSerialization.jsonObject(with: product.bytes, options: [.fragmentsAllowed]),
          "\(product.relativePath) is not JSON")
        XCTAssertTrue(product.text.hasSuffix("\n"), "\(product.relativePath) lacks its trailing LF")
        XCTAssertFalse(product.text.hasSuffix("\n\n"), "\(product.relativePath) ends with a blank line")
      } else if product.relativePath.hasSuffix(".jsonl") {
        let lines = product.text.split(separator: "\n", omittingEmptySubsequences: false)
        XCTAssertEqual(lines.count, 2, "\(product.relativePath) must be one line plus its delimiter")
        XCTAssertNoThrow(try JSONSerialization.jsonObject(with: Data(lines[0].utf8)))
      }
    }
    let yamlDocuments: [(String, JSONValue)] = [
      ("cli-command-registry.yaml", CLIMachineContracts.commandRegistryDocument()),
      ("cli-error-registry.yaml", CLIMachineContracts.errorRegistryDocument()),
      ("app-product-capability-registry.yaml", CLIMachineContracts.appRegistryDocument()),
    ]
    let products = Dictionary(
      uniqueKeysWithValues: try CLIMachineContracts.contractProducts().map { ($0.relativePath, $0) })
    for (name, document) in yamlDocuments {
      let product = try XCTUnwrap(products[name])
      XCTAssertTrue(product.text.hasPrefix("# Generated by `arkdeck maintainer contracts export`"))
      let parsed = try YAMLSubset.parse(product.text)
      XCTAssertEqual(parsed, document, "\(name) does not read back as the document it was rendered from")
    }
  }

