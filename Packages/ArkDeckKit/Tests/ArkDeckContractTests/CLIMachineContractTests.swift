// MARK: - Helpers

/// Foundation JSON to `JSONValue`, for reading committed products back.
enum JSONValueBridge {
  static func value(from data: Data) throws -> JSONValue {
    try value(JSONSerialization.jsonObject(with: data, options: [.fragmentsAllowed]))
  }

  static func value(_ object: Any) throws -> JSONValue {
    switch object {
    case is NSNull:
      return .null
    case let number as NSNumber:
      if CFGetTypeID(number) == CFBooleanGetTypeID() { return .bool(number.boolValue) }
      if let integer = Int64(exactly: number) { return .integer(integer) }
      return .number(number.doubleValue)
    case let text as String:
      return .string(text)
    case let items as [Any]:
      return .array(try items.map(value))
    case let fields as [String: Any]:
      return .object(try fields.mapValues(value))
    default:
      throw NSError(domain: "JSONValueBridge", code: 1, userInfo: [NSLocalizedDescriptionKey: "\(object)"])
    }
  }
}

/// A reader for exactly the YAML subset `ContractYAML` emits: block mappings
/// and sequences whose scalars, keys included, are JSON scalars. It exists so
/// the test can prove the YAML products read back as the documents they were
/// rendered from without a YAML library in the package.
enum YAMLSubset {
  struct Failure: Error { let message: String }

  static func parse(_ text: String) throws -> JSONValue {
    let lines = text.split(separator: "\n", omittingEmptySubsequences: false)
      .map(String.init)
      .filter { !$0.hasPrefix("#") && !$0.trimmingCharacters(in: .whitespaces).isEmpty }
    var cursor = 0
    let value = try parseBlock(lines, &cursor, indent: 0)
    guard cursor == lines.count else { throw Failure(message: "trailing content at line \(cursor)") }
    return value
  }

  private static func indentation(_ line: String) -> Int {
    line.prefix { $0 == " " }.count
  }

  private static func parseBlock(_ lines: [String], _ cursor: inout Int, indent: Int) throws -> JSONValue {
    guard cursor < lines.count else { throw Failure(message: "unexpected end") }
    let first = lines[cursor]
    guard indentation(first) == indent else { throw Failure(message: "bad indent at line \(cursor)") }
    let body = String(first.dropFirst(indent))
    if body.hasPrefix("- ") { return try parseSequence(lines, &cursor, indent: indent) }
    if body == "[]" || body == "{}" || !body.hasPrefix("\"") {
      cursor += 1
      return try scalar(body)
    }
    return try parseMapping(lines, &cursor, indent: indent)
  }

  private static func parseMapping(_ lines: [String], _ cursor: inout Int, indent: Int) throws -> JSONValue {
    var fields: [String: JSONValue] = [:]
    while cursor < lines.count, indentation(lines[cursor]) == indent, !lines[cursor].dropFirst(indent).hasPrefix("- ") {
      let body = String(lines[cursor].dropFirst(indent))
      let (keyText, rest) = try splitKey(body)
      guard case .string(let key) = try scalar(keyText) else { throw Failure(message: "key is not a string") }
      cursor += 1
      if rest.isEmpty {
        fields[key] = try parseBlock(lines, &cursor, indent: indent + 2)
      } else {
        fields[key] = try scalar(rest)
      }
    }
    return .object(fields)
  }

  private static func parseSequence(_ lines: [String], _ cursor: inout Int, indent: Int) throws -> JSONValue {
    var items: [JSONValue] = []
    while cursor < lines.count, indentation(lines[cursor]) == indent, lines[cursor].dropFirst(indent).hasPrefix("- ") {
      let rest = String(lines[cursor].dropFirst(indent + 2))
      // A quoted token followed by `:` opens a nested mapping on this line; a
      // bare quoted token is a scalar item.
      let opensMapping = rest.hasPrefix("\"") && (try? splitKey(rest)) != nil
      if opensMapping || rest.hasPrefix("- ") {
        // A nested block whose first line shares the `- ` line: re-indent it
        // and parse the block at indent + 2.
        var nested = [String(repeating: " ", count: indent + 2) + rest]
        cursor += 1
        while cursor < lines.count, indentation(lines[cursor]) >= indent + 2 {
          nested.append(lines[cursor])
          cursor += 1
        }
        var nestedCursor = 0
        items.append(try parseBlock(nested, &nestedCursor, indent: indent + 2))
        guard nestedCursor == nested.count else { throw Failure(message: "nested block not consumed") }
      } else {
        cursor += 1
        items.append(try scalar(rest))
      }
    }
    return .array(items)
  }

  /// Splits `"key": rest` into the quoted key and the remainder after `: `.
  private static func splitKey(_ body: String) throws -> (String, String) {
    guard body.hasPrefix("\"") else { throw Failure(message: "key is not quoted: \(body)") }
    var index = body.index(after: body.startIndex)
    var escaped = false
    while index < body.endIndex {
      let character = body[index]
      if escaped {
        escaped = false
      } else if character == "\\" {
        escaped = true
      } else if character == "\"" {
        let key = String(body[...index])
        let remainder = body[body.index(after: index)...]
        if remainder == ":" { return (key, "") }
        guard remainder.hasPrefix(": ") else { throw Failure(message: "malformed key line: \(body)") }
        return (key, String(remainder.dropFirst(2)))
      }
      index = body.index(after: index)
    }
    throw Failure(message: "unterminated key: \(body)")
  }

  private static func scalar(_ text: String) throws -> JSONValue {
    if text == "[]" { return .array([]) }
    if text == "{}" { return .object([:]) }
    return try JSONValueBridge.value(from: Data(text.utf8))
  }
}

/// A validator for exactly the JSON Schema 2020-12 vocabulary the bundle's
/// schemas use, so the tests can prove each schema accepts the real output
/// and rejects a counterexample without a schema library in the package.
enum JSONSchemaSubset {
  static func validate(_ value: JSONValue, against schema: JSONValue) -> Bool {
    validate(value, schema: schema, root: schema)
  }

  private static func resolve(_ ref: String, in root: JSONValue) -> JSONValue? {
    guard ref.hasPrefix("#/") else { return nil }
    var current = root
    for segment in ref.dropFirst(2).split(separator: "/") {
      guard case .object(let fields) = current, let next = fields[String(segment)] else { return nil }
      current = next
    }
    return current
  }

  private static func matchesType(_ value: JSONValue, _ type: String) -> Bool {
    switch (type, value) {
    case ("object", .object), ("array", .array), ("string", .string), ("boolean", .bool), ("null", .null):
      return true
    case ("integer", .integer), ("integer", .unsignedInteger):
      return true
    case ("number", .integer), ("number", .unsignedInteger), ("number", .number):
      return true
    default:
      return false
    }
  }

  private static func number(_ value: JSONValue) -> Double? {
    switch value {
    case .integer(let i): return Double(i)
    case .unsignedInteger(let u): return Double(u)
    case .number(let d): return d
    default: return nil
    }
  }

  private static func validate(_ value: JSONValue, schema: JSONValue, root: JSONValue) -> Bool {
    guard case .object(let s) = schema else { return true }
    if case .string(let ref)? = s["$ref"] {
      guard let target = resolve(ref, in: root), validate(value, schema: target, root: root) else { return false }
    }
    if let type = s["type"] {
      switch type {
      case .string(let name): if !matchesType(value, name) { return false }
      case .array(let names):
        if !names.contains(where: { if case .string(let name) = $0 { return matchesType(value, name) }; return false }) { return false }
      default: return false
      }
    }
    if let constant = s["const"], value != constant { return false }
    if case .array(let options)? = s["enum"], !options.contains(value) { return false }
    if case .object(let fields) = value {
      if case .array(let required)? = s["required"] {
        for case .string(let key) in required where fields[key] == nil { return false }
      }
      var properties: [String: JSONValue] = [:]
      if case .object(let declared)? = s["properties"] { properties = declared }
      for (key, sub) in properties {
        if let present = fields[key], !validate(present, schema: sub, root: root) { return false }
      }
      if s["additionalProperties"] == .bool(false) {
        for key in fields.keys where properties[key] == nil { return false }
      }
    }
    if case .array(let items) = value, let itemSchema = s["items"] {
      for item in items where !validate(item, schema: itemSchema, root: root) { return false }
    }
    if case .string(let text) = value {
      if case .integer(let minimum)? = s["minLength"], text.count < minimum { return false }
      if case .string(let pattern)? = s["pattern"] {
        guard let regex = try? NSRegularExpression(pattern: pattern),
          regex.firstMatch(in: text, range: NSRange(text.startIndex..., in: text)) != nil
        else { return false }
      }
    }
    if let numeric = number(value) {
      if let minimum = s["minimum"].flatMap(number), numeric < minimum { return false }
      if let maximum = s["maximum"].flatMap(number), numeric > maximum { return false }
    }
    if case .array(let options)? = s["oneOf"] {
      let matches = options.filter { validate(value, schema: $0, root: root) }.count
      if matches != 1 { return false }
    }
    if case .array(let options)? = s["anyOf"] {
      if !options.contains(where: { validate(value, schema: $0, root: root) }) { return false }
    }
    if case .array(let all)? = s["allOf"] {
      for sub in all where !validate(value, schema: sub, root: root) { return false }
    }
    if let negated = s["not"], validate(value, schema: negated, root: root) { return false }
    if let condition = s["if"] {
      if validate(value, schema: condition, root: root) {
        if let then = s["then"], !validate(value, schema: then, root: root) { return false }
      } else if let otherwise = s["else"], !validate(value, schema: otherwise, root: root) {
        return false
      }
    }
    return true
  }
}
