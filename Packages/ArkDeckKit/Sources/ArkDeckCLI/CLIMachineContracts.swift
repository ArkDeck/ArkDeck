        "text": .string("x"),
      ])
    ),
  ]

  /// Values the encoder must refuse. Recorded with the refusal it actually
  /// gives, so the bundle cannot claim a rejection this build does not make.
  static let canonicalRejectionInputs: [(name: String, value: JSONValue)] = [
    ("positiveInfinity", .number(Double.infinity)),
    ("negativeInfinity", .number(-Double.infinity)),
    ("nan", .number(Double.nan)),
    ("integerBeyondExactRange", .integer(Int64.max)),
    ("unsignedIntegerBeyondExactRange", .unsignedInteger(UInt64.max)),
  ]

  static func canonicalVectorsDocument() throws -> JSONValue {
    var vectors: [JSONValue] = []
    for input in canonicalVectorInputs {
      let canonical: String
      do {
        canonical = try CLICanonicalJSON.canonicalString(input.value)
      } catch {
        throw Failure("canonical vector \(input.name) is refused by this build: \(error)")
      }
      vectors.append(
        .object([
          "name": .string(input.name),
          "value": input.value,
          "canonical": .string(canonical),
        ]))
    }
    var rejections: [JSONValue] = []
    for input in canonicalRejectionInputs {
      do {
        let unexpected = try CLICanonicalJSON.canonicalString(input.value)
        throw Failure(
          "canonical rejection \(input.name) was accepted by this build as \(unexpected)")
      } catch let failure as Failure {
        throw failure
      } catch {
        rejections.append(
          .object([
            "name": .string(input.name),
            "reason": .string(String(describing: error)),
          ]))
      }
    }
    return .object([
      "schemaVersion": .string(canonicalVectorsSchemaVersion),
      "canonicalJsonVersion": .string(CLICanonicalJSON.version),
      "bundleVersion": .string(CLIProductVersion.machineContract),
      "cliVersion": .string(CLIProductVersion.product),
      "vectors": .array(vectors),
      "rejections": .array(rejections),
    ])
  }

