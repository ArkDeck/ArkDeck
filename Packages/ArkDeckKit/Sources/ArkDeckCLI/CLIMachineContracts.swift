    static let macOSOnlyRoots: Set<String> = ["legacy", "agentd", "signing", "update-feed", "maintainer"]
    static let macOSOnlyRuntimeGroups: Set<String> = [
      "service", "signing", "bundle", "tool", "update", "support-bundle",
    ]

    struct LeafIndex {
      let ordered: [(path: [String], leaf: CLILeafSpec)]
      let byCommand: [String: (path: [String], leaf: CLILeafSpec)]
      let byPath: [[String]: String]

      init() throws {
        let ordered = CLICommandRegistry.allLeaves()
        var byCommand: [String: (path: [String], leaf: CLILeafSpec)] = [:]
        var byPath: [[String]: String] = [:]
        for entry in ordered {
          guard byCommand[entry.leaf.canonicalCommand] == nil else {
            throw Failure("canonical command \(entry.leaf.canonicalCommand) is declared twice")
          }
          byCommand[entry.leaf.canonicalCommand] = entry
          byPath[entry.path] = entry.leaf.canonicalCommand
        }
        self.ordered = ordered
        self.byCommand = byCommand
        self.byPath = byPath
      }

      func leaf(_ command: String) throws -> (path: [String], leaf: CLILeafSpec) {
        guard let found = byCommand[command] else {
          throw Failure("coverage names an unknown command \(command)")
        }
        return found
      }

      /// The leaf an argv pattern such as `arkdeck job status --job <id>` names.
      func resolve(pattern: String) throws -> (path: [String], leaf: CLILeafSpec) {
        let tokens = pattern.split(separator: " ").map(String.init)
        guard tokens.first == "arkdeck" else {
          throw Failure("argv pattern does not start with arkdeck: \(pattern)")
        }
        var path: [String] = []
        for token in tokens.dropFirst() {
          guard !token.hasPrefix("-"), !token.hasPrefix("<"), !token.hasPrefix("("),
            !token.hasPrefix("["), token != "..."
          else { break }
          let candidate = path + [token]
          guard byPath.keys.contains(where: { $0.starts(with: candidate) }) else { break }
          path = candidate
        }
        guard let command = byPath[path] else {
          throw Failure("argv pattern does not name a command: \(pattern)")
        }
        return try leaf(command)
      }
    }

    static func isLocal(path: [String], command: String) -> Bool {
      if directCommandsUnderLocalGroups.contains(command) { return false }
      if let root = path.first, localRoots.contains(root) { return true }
      if path.count > 1, path[0] == "runtime", localRuntimeGroups.contains(path[1]) { return true }
      if localCommands.contains(command) { return true }
      return localCommandPrefixes.contains { command.hasPrefix($0) }
    }

    static func classification(path: [String], leaf: CLILeafSpec) -> String {
      switch leaf.kind {
      case .tombstone, .refused:
        return ProductCoverageClassification.refused.rawValue
      case .executable:
        return isLocal(path: path, command: leaf.canonicalCommand)
          ? ProductCoverageClassification.local.rawValue
          : ProductCoverageClassification.direct.rawValue
      }
    }

    static func lifecycle(of leaf: CLILeafSpec) -> String {
      if case .tombstone = leaf.kind { return "removed" }
      return leaf.lifecycle.rawValue
    }

    static func requiredPlatforms(path: [String], leaf: CLILeafSpec) -> [String] {
      if let root = path.first, macOSOnlyRoots.contains(root) { return ["macos"] }
      if path.count > 1, path[0] == "runtime", macOSOnlyRuntimeGroups.contains(path[1]) {
        return ["macos"]
      }
      if leaf.lifecycle == .legacy { return ["macos"] }
      if case .tombstone = leaf.kind { return ["macos"] }
      return platformVocabulary
    }

    /// The exact argv that reaches a leaf: its path, its required options
    /// with their placeholders, one member of each exactly-one group and its
    /// required positionals.
    static func targetCommand(path: [String], leaf: CLILeafSpec) -> String {
      var tokens = ["arkdeck"] + path
      for option in leaf.options where option.isRequired && option.isPublished {
        tokens.append(option.name)
        if case .value(let placeholder, _) = option.form { tokens.append("<\(placeholder)>") }
      }
      for group in leaf.requiresExactlyOneOf {
        let members = group.map { name -> String in
          guard let option = leaf.options.first(where: { $0.name == name }),
            case .value(let placeholder, _) = option.form
          else { return name }
          return "\(name) <\(placeholder)>"
        }
        tokens.append("(" + members.joined(separator: " | ") + ")")
      }
      for positional in leaf.positionals where positional.isRequired {
        tokens.append("<\(positional.name)>")
      }
      return tokens.joined(separator: " ")
    }

    static func fixture(for leaf: CLILeafSpec) -> String { "argv/\(leaf.canonicalCommand).json" }

    static func build() throws -> Coverage {
      let index = try LeafIndex()
      var entries: [Entry] = []

      // Daemon control methods.
      let methods = CLIControlMethodRegistry.classifiedMethods.sorted()
      for method in methods {
        guard let coverage = daemonMethodCoverage[method] else {
          throw Failure("daemon method \(method) has no coverage ruling")
        }
        entries.append(try daemonEntry(method: method, coverage: coverage, index: index))
      }
      for unknown in daemonMethodCoverage.keys.sorted()
      where !CLIControlMethodRegistry.classifiedMethods.contains(unknown) {
        throw Failure("coverage names a daemon method the registry does not classify: \(unknown)")
      }
      // Published Catalog operations.
      let operations = RuntimeOperationCatalog.operations.sorted { $0.reference < $1.reference }
      let submit = try index.leaf("job.submit")
      for descriptor in operations {
        let fronting = index.ordered.filter { $0.leaf.catalogOperation == descriptor.reference }
        var entry: Entry
        if let first = fronting.first {
          entry = Entry(
            feature: descriptor.reference,
            source: "catalog:\(descriptor.reference)",
            classification: classification(path: first.path, leaf: first.leaf),
            targetClassification: classification(path: first.path, leaf: first.leaf),
            lifecycle: lifecycle(of: first.leaf),
            targetCommand: targetCommand(path: first.path, leaf: first.leaf),
            equivalentCommands: fronting.dropFirst().map { targetCommand(path: $0.path, leaf: $0.leaf) },
            conformanceFixture: fixture(for: first.leaf),
            requiredPlatforms: requiredPlatforms(path: first.path, leaf: first.leaf),
            referencedLeaves: fronting.map(\.leaf.canonicalCommand))
        } else {
          for option in ["--operation", "--inputs-file"]
          where !submit.leaf.options.contains(where: { $0.name == option }) {
            throw Failure("job submit no longer accepts \(option); generic coverage is unreachable")
          }
          entry = Entry(
            feature: descriptor.reference,
            source: "catalog:\(descriptor.reference)",
            classification: ProductCoverageClassification.generic.rawValue,
            targetClassification: ProductCoverageClassification.generic.rawValue,
            lifecycle: "current",
            targetCommand:
              "arkdeck job submit --operation \(descriptor.reference) --inputs-file <path>",
            conformanceFixture: fixture(for: submit.leaf),
            requiredPlatforms: platformVocabulary,
            referencedLeaves: [])
        }
        if let alias = descriptor.aliasFor { entry.note = "alias of \(alias)" }
        entries.append(entry)
      }

      // App product capabilities.
      for capability in AppProductCapabilityRegistry.capabilities.sorted(by: { $0.id < $1.id }) {
        var resolved: [(path: [String], leaf: CLILeafSpec)] = []
        for pattern in capability.cliEquivalent {
          resolved.append(try index.resolve(pattern: pattern))
        }
        entries.append(
          Entry(
            feature: capability.id,
            source: "app:\(capability.surface)",
            classification: capability.classification.rawValue,
            targetClassification: capability.classification.rawValue,
            lifecycle: "current",
            targetCommand: capability.cliEquivalent.first,
            equivalentCommands: Array(capability.cliEquivalent.dropFirst()),
            conformanceFixture: resolved.first.map { fixture(for: $0.leaf) },
            requiredPlatforms: ["macos"],
            owner: capability.owner,
            note: capability.title,
            referencedLeaves: resolved.map(\.leaf.canonicalCommand)))
      }

      // Leaves nothing above reaches: they are features in their own right.
      let referenced = Set(entries.flatMap(\.referencedLeaves))
      for (path, leaf) in index.ordered where !referenced.contains(leaf.canonicalCommand) {
        var entry = Entry(
          feature: leaf.canonicalCommand,
          source: "cli:\(leaf.canonicalCommand)",
          classification: classification(path: path, leaf: leaf),
          targetClassification: classification(path: path, leaf: leaf),
          lifecycle: lifecycle(of: leaf),
          targetCommand: targetCommand(path: path, leaf: leaf),
          conformanceFixture: fixture(for: leaf),
          requiredPlatforms: requiredPlatforms(path: path, leaf: leaf),
          referencedLeaves: [leaf.canonicalCommand])
        switch leaf.kind {
        case .tombstone(let tombstone):
          entry.note = tombstone.replacementArgvPattern.map { "replaced by `\($0)`" }
            ?? tombstone.reason
        case .refused(let reason):
          entry.note = reason
        case .executable:
          if let replacement = leaf.replacementArgvPattern {
            entry.note = "superseded by `\(replacement)`"
          }
        }
        entries.append(entry)
      }

      try validate(entries, index: index)
      entries.sort { $0.feature < $1.feature }
      return Coverage(entries: entries, document: document(for: entries))
    }

    private static func daemonEntry(
      method: String, coverage: DaemonCoverage, index: LeafIndex
    ) throws -> Entry {
      switch coverage {
      case .leaf(let command, let lifecycleOverride, let note, let also):
        let found = try index.leaf(command)
        guard case .executable = found.leaf.kind else {
          throw Failure("daemon method \(method) is fronted by a non-executable leaf \(command)")
        }
        var equivalents: [String] = []
        for alias in also {
          let aliasLeaf = try index.leaf(alias)
          guard case .executable = aliasLeaf.leaf.kind, aliasLeaf.leaf.lifecycle != .current else {
            throw Failure("daemon method \(method) names \(alias) as a compatibility spelling, but it is current")
          }
          equivalents.append(targetCommand(path: aliasLeaf.path, leaf: aliasLeaf.leaf))
        }
        return Entry(
          feature: method,
          source: "daemon:\(method)",
          classification: classification(path: found.path, leaf: found.leaf),
          targetClassification: classification(path: found.path, leaf: found.leaf),
          lifecycle: lifecycleOverride ?? lifecycle(of: found.leaf),
          targetCommand: targetCommand(path: found.path, leaf: found.leaf),
          equivalentCommands: equivalents,
          conformanceFixture: fixture(for: found.leaf),
          requiredPlatforms: requiredPlatforms(path: found.path, leaf: found.leaf),
          note: note,
          referencedLeaves: [command] + also)
      case .plumbing(let behind, let note):
        let found = try index.leaf(behind)
        return Entry(
          feature: method,
          source: "daemon:\(method)",
          classification: ProductCoverageClassification.internal.rawValue,
          targetClassification: ProductCoverageClassification.internal.rawValue,
          lifecycle: lifecycle(of: found.leaf),
          targetCommand: targetCommand(path: found.path, leaf: found.leaf),
          conformanceFixture: fixture(for: found.leaf),
          requiredPlatforms: requiredPlatforms(path: found.path, leaf: found.leaf),
          note: note,
          referencedLeaves: [behind])
      case .refused(let command, let note):
        let found = try index.leaf(command)
        guard case .refused = found.leaf.kind else {
          throw Failure("daemon method \(method) is marked refused but \(command) is not a refused leaf")
        }
        return Entry(
          feature: method,
          source: "daemon:\(method)",
          classification: ProductCoverageClassification.refused.rawValue,
          targetClassification: ProductCoverageClassification.refused.rawValue,
          lifecycle: lifecycle(of: found.leaf),
          targetCommand: targetCommand(path: found.path, leaf: found.leaf),
          conformanceFixture: fixture(for: found.leaf),
          requiredPlatforms: requiredPlatforms(path: found.path, leaf: found.leaf),
          note: note,
          referencedLeaves: [command])
      }
    }

    private static func validate(_ entries: [Entry], index: LeafIndex) throws {
      var features: Set<String> = []
      let classifications = Set(classificationVocabulary)
      let lifecycles = Set(lifecycleVocabulary)
      for entry in entries {
        guard features.insert(entry.feature).inserted else {
          throw Failure("feature \(entry.feature) is covered twice")
        }
        guard classifications.contains(entry.classification),
          classifications.contains(entry.targetClassification)
        else { throw Failure("feature \(entry.feature) uses an unknown classification") }
        guard lifecycles.contains(entry.lifecycle) else {
          throw Failure("feature \(entry.feature) uses an unknown lifecycle \(entry.lifecycle)")
        }
        guard entry.classification == entry.targetClassification
          || entry.classification == ProductCoverageClassification.blocked.rawValue
        else {
          throw Failure("feature \(entry.feature) claims a target it has not reached")
        }
        for pattern in [entry.targetCommand].compactMap({ $0 }) + entry.equivalentCommands {
          _ = try index.resolve(pattern: pattern)
        }
        for command in entry.referencedLeaves { _ = try index.leaf(command) }
      }
      let referenced = Set(entries.flatMap(\.referencedLeaves))
      for entry in index.ordered where !referenced.contains(entry.leaf.canonicalCommand) {
        throw Failure("leaf \(entry.leaf.canonicalCommand) is not covered")
      }
    }

    private static func document(for entries: [Entry]) -> JSONValue {
      var byClassification: [String: Int64] = [:]
      var bySource: [String: Int64] = [:]
      for entry in entries {
        byClassification[entry.classification, default: 0] += 1
        let kind = String(entry.source.prefix { $0 != ":" })
        bySource[kind, default: 0] += 1
      }
      let blocked = entries
        .filter { $0.classification == ProductCoverageClassification.blocked.rawValue }
        .map { JSONValue.string($0.feature) }
      return .object([
        "schemaVersion": .string(featureCoverageSchemaVersion),
        "bundleVersion": .string(CLIProductVersion.machineContract),
        "cliVersion": .string(CLIProductVersion.product),
        "catalogDigest": .string(RuntimeOperationCatalog.catalogDigest),
        "commandRegistrySchemaVersion": .string(CLICommandRegistry.schemaVersion),
        "appCapabilityRegistrySchemaVersion": .string(AppProductCapabilityRegistry.schemaVersion),
        "classificationVocabulary": .array(classificationVocabulary.map(JSONValue.string)),
        "lifecycleVocabulary": .array(lifecycleVocabulary.map(JSONValue.string)),
        "platformVocabulary": .array(platformVocabulary.map(JSONValue.string)),
        "summary": .object([
          "entries": .integer(Int64(entries.count)),
          "byClassification": .object(byClassification.mapValues(JSONValue.integer)),
          "bySource": .object(bySource.mapValues(JSONValue.integer)),
          "blocked": .array(blocked),
          "fullFunction": .bool(blocked.isEmpty),
        ]),
        "entries": .array(entries.map(\.document)),
      ])
    }
  }

  // MARK: Argv fixtures

  enum ArgvFixtures {
    static func sample(for grammar: CLIValueGrammar) -> String {
      switch grammar {
      case .opaque: return "sample"
      case .positiveInteger(let range): return String(range.lowerBound)
      case .nonNegativeInteger(let range): return String(range.lowerBound)
      case .enumeration(let values): return values.first ?? "sample"
      case .hexDigest(let length): return String(repeating: "0", count: length)
      case .controlRequestID: return fixtureControlRequestID
      case .duration(let maximumMilliseconds): return maximumMilliseconds >= 1000 ? "1s" : "1ms"
      }
    }

    static func validArgv(path: [String], leaf: CLILeafSpec) -> [String] {
      var argv = path
      var present: Set<String> = []
      func add(_ option: CLIOptionSpec) {
        argv.append(option.name)
        present.insert(option.name)
        if case .value(_, let grammar) = option.form { argv.append(sample(for: grammar)) }
      }
      for option in leaf.options where option.isRequired && option.isPublished { add(option) }
      for group in leaf.requiresExactlyOneOf where !group.contains(where: present.contains) {
        if let option = leaf.options.first(where: { group.contains($0.name) }) { add(option) }
      }
      for positional in leaf.positionals where positional.isRequired {
        argv.append(sample(for: positional.grammar))
      }
      return argv
    }

    static func outcome(_ result: Result<CLIInvocation, CLIRegistryError>) -> JSONValue {
      switch result {
      case .success(let invocation):
        switch invocation {
        case .rootHelp:
          return .object(["outcome": .string("rootHelp")])
        case .nodeHelp(let node):
          return .object(["outcome": .string("nodeHelp"), "node": .string(node.token)])
        case .leafHelp(_, let leaf):
          return .object(["outcome": .string("leafHelp"), "command": .string(leaf.canonicalCommand)])
        case .version(let mode):
          return .object(["outcome": .string("version"), "outputMode": .string(mode.rawValue)])
        case .commands(let mode):
          return .object(["outcome": .string("commands"), "outputMode": .string(mode.rawValue)])
        case .completion(let shell):
          return .object(["outcome": .string("completion"), "shell": .string(shell)])
        case .dispatch(_, let leaf, let handlerArguments):
          return .object([
            "outcome": .string("dispatch"),
            "command": .string(leaf.canonicalCommand),
            "handlerArguments": .array(handlerArguments.map(JSONValue.string)),
          ])
        }
      case .failure(let error):
        var fields: [String: JSONValue] = [
          "outcome": .string("failure"),
          "code": .string(error.code.rawValue),
          "category": .string(error.code.category.machineCategory),
          "exitCode": .integer(Int64(error.exitCode)),
        ]
        if let command = error.command { fields["command"] = .string(command) }
        if error.lifecycle != .current { fields["lifecycleStatus"] = .string(error.lifecycle.rawValue) }
        if let replacement = error.replacementArgvPattern {
          fields["replacementArgvPattern"] = .string(replacement)
        }
        return .object(fields)
      }
    }

    static func document(path: [String], leaf: CLILeafSpec) throws -> JSONValue {
      let valid = validArgv(path: path, leaf: leaf)
      var cases: [(name: String, argv: [String])] = [("valid", valid), ("leafHelp", path + ["--help"])]
      if case .executable = leaf.kind {
        cases.append(("unknownOption", valid + ["--no-such-option"]))
        if let option = leaf.options.first(where: { $0.isRequired && $0.isPublished }) {
          var duplicate = valid + [option.name]
          if case .value(_, let grammar) = option.form { duplicate.append(sample(for: grammar)) }
          cases.append(("duplicateOption", duplicate))
        }
        if leaf.options.contains(where: { $0.isRequired && $0.isPublished })
          || !leaf.requiresExactlyOneOf.isEmpty
          || leaf.positionals.contains(where: \.isRequired)
        {
          cases.append(("missingRequired", path))
        }
        if leaf.options.contains(where: { $0.name == "--output" }), !leaf.outputModes.contains(.jsonl) {
          cases.append(("jsonlRefused", valid + ["--output", "jsonl"]))
        }
        if !leaf.connectsToRuntime, !leaf.options.contains(where: { $0.name == "--endpoint" }) {
          cases.append(("endpointRefused", valid + ["--endpoint", "local"]))
        }
        if let compatibility = leaf.options.first(where: { $0.stability == .macosCompatibilityOnly }),
          case .value(_, let grammar) = compatibility.form
        {
          cases.append(("macosCompatibilityOption", valid + [compatibility.name, sample(for: grammar)]))
        }
        let parsed = CLIArgumentParser.parse(valid)
        guard case .success(let invocation) = parsed else {
          throw Failure("the generated valid argv for \(leaf.canonicalCommand) is refused: \(valid)")
        }
        if case .dispatch(_, let dispatched, _) = invocation,
          dispatched.canonicalCommand != leaf.canonicalCommand
        {
          throw Failure("the generated valid argv for \(leaf.canonicalCommand) dispatches elsewhere")
        }
      }
      let rendered: [JSONValue] = cases.map { entry in
        .object([
          "name": .string(entry.name),
          "argv": .array(entry.argv.map(JSONValue.string)),
          "expected": outcome(CLIArgumentParser.parse(entry.argv)),
        ])
      }
      let kind: String
      switch leaf.kind {
      case .executable: kind = "executable"
      case .tombstone: kind = "tombstone"
      case .refused: kind = "refused"
      }
      return .object([
        "schemaVersion": .string(argvFixtureSchemaVersion),
        "cliVersion": .string(CLIProductVersion.product),
        "command": .string(leaf.canonicalCommand),
        "path": .array(path.map(JSONValue.string)),
        "kind": .string(kind),
        "lifecycleStatus": .string(FeatureCoverage.lifecycle(of: leaf)),
        "cases": .array(rendered),
      ])
    }
  }

