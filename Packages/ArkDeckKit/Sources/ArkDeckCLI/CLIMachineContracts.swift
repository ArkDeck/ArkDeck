/// The §14 machine-contract bundle, generated from the build that publishes it.
///
/// Every product here is a projection of something the binary already owns:
/// the command registry, the error registry, the canonical-JSON encoder, the
/// control-method registry, the published Catalog and the App capability
/// registry. Nothing is restated. `arkdeck maintainer contracts export` writes
/// the projections to `openspec/contracts/` and the conformance fixtures next
/// to the contract tests; `arkdeck maintainer contracts check` holds the
/// committed files to the build, so a registry change that forgets to
/// regenerate the bundle fails the gate rather than shipping a contract that
/// describes the previous binary.
///
/// The bundle is language-neutral on purpose (§14): a native port reads the
/// YAML/JSON and replays the argv fixtures through its own parser, and the
/// feature-coverage table is where "full function" (§18) is decided — by a
/// closed classification of every daemon method, Catalog operation, App
/// capability and CLI leaf, not by prose.
enum CLIMachineContracts {

