    /// One closed branch of the §7.3 union.
    static func branch(
      kind: String, ownerKinds: [String], resourceKinds: [String], reasonCodes: [String]?,
      extra: [String: JSONValue], required: [String], resourceMirrorsOwner: Bool
    ) -> JSONValue {
      var properties: [String: JSONValue] = [
        "kind": .object(["const": .string(kind)]),
        "owner": ownerObject(kinds: ownerKinds),
        "resource": ownerObject(kinds: resourceKinds),
        "reasonCode": reasonCodes.map { .object(["enum": strings($0)]) }
          ?? .object(["type": .string("string"), "minLength": .integer(1)]),
      ]
      for (key, value) in extra { properties[key] = value }
      var fields: [String: JSONValue] = [
        "type": .string("object"),
        "required": strings(["kind", "owner", "resource", "reasonCode"] + required),
        "properties": .object(properties),
        "additionalProperties": .bool(false),
      ]
      if resourceMirrorsOwner {
        fields["allOf"] = .array(
          ownerKinds.map { ownerKind in
            .object([
              "if": .object([
                "properties": .object([
                  "owner": .object(["properties": .object(["kind": .object(["const": .string(ownerKind)])])])
                ])
              ]),
              "then": .object([
                "properties": .object([
                  "resource": .object(["properties": .object(["kind": .object(["const": .string(ownerKind)])])])
                ])
              ]),
            ])
          })
      }
      return .object(fields)
    }

