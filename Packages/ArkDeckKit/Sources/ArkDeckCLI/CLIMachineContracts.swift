  enum FeatureCoverage {
    static let classificationVocabulary = ProductCoverageClassification.allCases.map(\.rawValue)
    static let lifecycleVocabulary = ["current", "deprecated", "legacy", "removed"]
    static let platformVocabulary = ["macos", "windows"]

    struct Entry {
      var feature: String
      var source: String
      var classification: String
      var targetClassification: String
      var lifecycle: String
      var targetCommand: String?
      var equivalentCommands: [String] = []
      var conformanceFixture: String?
      var requiredPlatforms: [String]
      var owner: String?
      var note: String?
      /// Canonical commands this entry reaches; not serialized.
      var referencedLeaves: [String] = []

      var document: JSONValue {
        var fields: [String: JSONValue] = [
          "feature": .string(feature),
          "source": .string(source),
          "classification": .string(classification),
          "targetClassification": .string(targetClassification),
          "lifecycle": .string(lifecycle),
          "targetCommand": targetCommand.map(JSONValue.string) ?? .null,
          "equivalentCommands": .array(equivalentCommands.map(JSONValue.string)),
          "conformanceFixture": conformanceFixture.map(JSONValue.string) ?? .null,
          "requiredPlatforms": .array(requiredPlatforms.map(JSONValue.string)),
          "implementationStatusByPlatform": .object(
            Dictionary(
              uniqueKeysWithValues: requiredPlatforms.map { platform in
                (platform, JSONValue.string(implementationStatus(on: platform)))
              })),
        ]
        if let owner { fields["owner"] = .string(owner) }
        if let note { fields["note"] = .string(note) }
        return .object(fields)
      }

      /// §14's closed status set. `implemented` on macOS means the entry's
      /// contract, registry mapping and fixture are closed — a tombstone or a
      /// refused stub that refuses exactly as contracted is implemented too;
      /// `blocked` is `partial`; a platform without a ratified profile is
      /// never reported as anything but `notImplemented`.
      func implementationStatus(on platform: String) -> String {
        guard platform == "macos" else { return "notImplemented" }
        return classification == ProductCoverageClassification.blocked.rawValue
          ? "partial" : "implemented"
      }
    }

