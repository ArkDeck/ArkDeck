// MARK: - Deterministic renderers

/// Pretty JSON with keys in `arkdeck.cli.canonical-json/1` order (UTF-16 code
/// unit), two-space indentation and one trailing LF. Scalars are rendered by
/// the canonical encoder so a port re-encoding a product reproduces it.
enum ContractJSON {
  static func document(_ value: JSONValue) -> Data {
    var out = ""
    render(value, indent: 0, into: &out)
    out += "\n"
    return Data(out.utf8)
  }

  static func scalar(_ value: JSONValue) -> String {
    (try? CLICanonicalJSON.canonicalString(value)) ?? "null"
  }

  static func sortedKeys(_ fields: [String: JSONValue]) -> [String] {
    fields.keys.sorted { $0.utf16.lexicographicallyPrecedes($1.utf16) }
  }

  private static func render(_ value: JSONValue, indent: Int, into out: inout String) {
    let pad = String(repeating: "  ", count: indent)
    switch value {
    case .object(let fields):
      guard !fields.isEmpty else { out += "{}"; return }
      out += "{\n"
      let keys = sortedKeys(fields)
      for (offset, key) in keys.enumerated() {
        out += pad + "  " + scalar(.string(key)) + ": "
        render(fields[key]!, indent: indent + 1, into: &out)
        out += offset == keys.count - 1 ? "\n" : ",\n"
      }
      out += pad + "}"
    case .array(let items):
      guard !items.isEmpty else { out += "[]"; return }
      out += "[\n"
      for (offset, item) in items.enumerated() {
        out += pad + "  "
        render(item, indent: indent + 1, into: &out)
        out += offset == items.count - 1 ? "\n" : ",\n"
      }
      out += pad + "]"
    default:
      out += scalar(value)
    }
  }
}

/// The YAML subset the bundle uses: block mappings and sequences whose every
/// scalar — keys included — is a JSON scalar. YAML 1.2 double-quoted scalars
/// share JSON's escapes, so the same canonical encoder renders both products
/// and a YAML reader and a JSON reader see the same values.
enum ContractYAML {
  static func document(_ value: JSONValue) -> Data {
    var out = "# \(CLIMachineContracts.generatedNotice)\n"
    out += lines(value).joined(separator: "\n") + "\n"
    return Data(out.utf8)
  }

  private static func isScalar(_ value: JSONValue) -> Bool {
    switch value {
    case .object(let fields): return fields.isEmpty
    case .array(let items): return items.isEmpty
    default: return true
    }
  }

  private static func scalar(_ value: JSONValue) -> String {
    switch value {
    case .object: return "{}"
    case .array: return "[]"
    default: return ContractJSON.scalar(value)
    }
  }

  static func lines(_ value: JSONValue) -> [String] {
    switch value {
    case .object(let fields):
      guard !fields.isEmpty else { return ["{}"] }
      var out: [String] = []
      for key in ContractJSON.sortedKeys(fields) {
        let child = fields[key]!
        let rendered = ContractJSON.scalar(.string(key))
        if isScalar(child) {
          out.append("\(rendered): \(scalar(child))")
        } else {
          out.append("\(rendered):")
          out += lines(child).map { "  " + $0 }
        }
      }
      return out
    case .array(let items):
      guard !items.isEmpty else { return ["[]"] }
      var out: [String] = []
      for item in items {
        if isScalar(item) {
          out.append("- \(scalar(item))")
        } else {
          let nested = lines(item)
          out.append("- " + nested[0])
          out += nested.dropFirst().map { "  " + $0 }
        }
      }
      return out
    default:
      return [scalar(value)]
    }
  }
}
