  struct Failure: Error, CustomStringConvertible {
    let message: String
    init(_ message: String) { self.message = message }
    var description: String { message }
  }

  /// One generated file: a path relative to its root, and its exact bytes.
  struct Product: Equatable {
    let relativePath: String
    let bytes: Data
    var text: String { String(decoding: bytes, as: UTF8.self) }
  }

  // MARK: Products

  static func contractProducts() throws -> [Product] {
    let coverage = try FeatureCoverage.build()
    let products: [(String, Data)] = [
      ("cli-command-registry.yaml", ContractYAML.document(commandRegistryDocument())),
      ("cli-error-registry.yaml", ContractYAML.document(errorRegistryDocument())),
      ("cli-canonical-json-vectors.json", ContractJSON.document(try canonicalVectorsDocument())),
      ("cli-feature-coverage.json", ContractJSON.document(coverage.document)),
      ("app-product-capability-registry.yaml", ContractYAML.document(appRegistryDocument())),
      ("cli-result.schema.json", ContractJSON.document(Schemas.result)),
      ("cli-page.schema.json", ContractJSON.document(Schemas.page)),
      ("cli-event.schema.json", ContractJSON.document(Schemas.event)),
      ("cli-next-action.schema.json", ContractJSON.document(Schemas.nextAction)),
      ("runtime-control-plane.schema.json", ContractJSON.document(Schemas.controlPlane)),
    ]
    let paths = products.map(\.0)
    guard paths == contractRelativePaths else {
      throw Failure("the contract product list drifted from its declared file names")
    }
    return products.map { Product(relativePath: $0.0, bytes: $0.1) }
  }

  static func fixtureProducts() throws -> [Product] {
    var products: [Product] = []
    var seen: Set<String> = []
    for (path, leaf) in CLICommandRegistry.allLeaves() {
      guard seen.insert(leaf.canonicalCommand).inserted else {
        throw Failure("canonical command \(leaf.canonicalCommand) is declared twice")
      }
      let document = try ArgvFixtures.document(path: path, leaf: leaf)
      products.append(
        Product(
          relativePath: "argv/\(leaf.canonicalCommand).json",
          bytes: ContractJSON.document(document)))
    }
    products += try EnvelopeFixtures.products()
    products += SampleDocuments.products()
    let index: JSONValue = .object([
      "schemaVersion": .string(fixtureIndexSchemaVersion),
      "bundleVersion": .string(CLIProductVersion.machineContract),
      "cliVersion": .string(CLIProductVersion.product),
      "argvFixtureSchemaVersion": .string(argvFixtureSchemaVersion),
      "envelopeFixtureSchemaVersion": .string(envelopeFixtureSchemaVersion),
      "controlRequestId": .string(fixtureControlRequestID),
      "files": .array(products.map(\.relativePath).sorted().map(JSONValue.string)),
    ])
    products.append(Product(relativePath: "index.json", bytes: ContractJSON.document(index)))
    return products.sorted { $0.relativePath < $1.relativePath }
  }

  // MARK: Export and drift

  struct ExportReport {
    var written: [String] = []
    var removed: [String] = []
  }

  struct CheckReport {
    var drifted: [String] = []
    var missing: [String] = []
    var unexpected: [String] = []
    var checked = 0
    var isClean: Bool { drifted.isEmpty && missing.isEmpty && unexpected.isEmpty }

    var document: JSONValue {
      .object([
        "clean": .bool(isClean),
        "checked": .integer(Int64(checked)),
        "drifted": .array(drifted.map(JSONValue.string)),
        "missing": .array(missing.map(JSONValue.string)),
        "unexpected": .array(unexpected.map(JSONValue.string)),
      ])
    }
  }

  static func export(contractsDirectory: URL, fixturesDirectory: URL) throws -> ExportReport {
    let contracts = try contractProducts()
    let fixtures = try fixtureProducts()
    var report = ExportReport()
    for product in contracts {
      try write(product, under: contractsDirectory)
      report.written.append("contracts/\(product.relativePath)")
    }
    let expected = Set(fixtures.map(\.relativePath))
    for stale in try regularFiles(under: fixturesDirectory) where !expected.contains(stale) {
      try FileManager.default.removeItem(at: fixturesDirectory.appendingPathComponent(stale))
      report.removed.append("fixtures/\(stale)")
    }
    for product in fixtures {
      try write(product, under: fixturesDirectory)
      report.written.append("fixtures/\(product.relativePath)")
    }
    return report
  }

  static func check(contractsDirectory: URL, fixturesDirectory: URL) throws -> CheckReport {
    var report = CheckReport()
    for product in try contractProducts() {
      compare(product, under: contractsDirectory, label: "contracts", into: &report)
    }
    let fixtures = try fixtureProducts()
    for product in fixtures {
      compare(product, under: fixturesDirectory, label: "fixtures", into: &report)
    }
    let expected = Set(fixtures.map(\.relativePath))
    for extra in try regularFiles(under: fixturesDirectory) where !expected.contains(extra) {
      report.unexpected.append("fixtures/\(extra)")
    }
    report.unexpected.sort()
    return report
  }

  private static func compare(
    _ product: Product, under root: URL, label: String, into report: inout CheckReport
  ) {
    report.checked += 1
    let url = root.appendingPathComponent(product.relativePath)
    guard let existing = try? Data(contentsOf: url) else {
      report.missing.append("\(label)/\(product.relativePath)")
      return
    }
    if existing != product.bytes { report.drifted.append("\(label)/\(product.relativePath)") }
  }

  private static func write(_ product: Product, under root: URL) throws {
    let url = root.appendingPathComponent(product.relativePath)
    try FileManager.default.createDirectory(
      at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
    try product.bytes.write(to: url, options: .atomic)
  }

  /// Every regular file under `root`, as a sorted relative path list. Hidden
  /// files are skipped so a Finder sidecar never counts as a stray fixture.
  private static func regularFiles(under root: URL) throws -> [String] {
    var isDirectory: ObjCBool = false
    guard FileManager.default.fileExists(atPath: root.path, isDirectory: &isDirectory),
      isDirectory.boolValue
    else { return [] }
    guard
      let enumerator = FileManager.default.enumerator(
        at: root, includingPropertiesForKeys: [.isRegularFileKey], options: [.skipsHiddenFiles])
    else { return [] }
    var found: [String] = []
    let prefix = root.standardizedFileURL.path + "/"
    for case let url as URL in enumerator {
      guard (try? url.resourceValues(forKeys: [.isRegularFileKey]).isRegularFile) == true else {
        continue
      }
      let path = url.standardizedFileURL.path
      guard path.hasPrefix(prefix) else { continue }
      found.append(String(path.dropFirst(prefix.count)))
    }
    return found.sorted()
  }

  // MARK: Registry projections

  static func commandRegistryDocument() -> JSONValue {
    var commands: JSONValue = .array([])
    if case .object(let projection) = CLIRegistryProjection.result(),
      let published = projection["commands"]
    {
      commands = published
    }
    return .object([
      "schemaVersion": .string(CLICommandRegistry.schemaVersion),
      "bundleVersion": .string(CLIProductVersion.machineContract),
      "cliVersion": .string(CLIProductVersion.product),
      "catalogDigest": .string(RuntimeOperationCatalog.catalogDigest),
      "commands": commands,
    ])
  }

  static func errorRegistryDocument() -> JSONValue {
    let categories: [JSONValue] = CLIExitCategory.allCases.map { category in
      .object([
        "category": .string(category.machineCategory),
        "exitCode": .integer(Int64(category.exitCode)),
        "codes": .array(
          CLIErrorCode.allCases.filter { $0.category == category }
            .map { .string($0.rawValue) }),
      ])
    }
    let codes: [JSONValue] = CLIErrorCode.allCases.map { code in
      .object([
        "code": .string(code.rawValue),
        "category": .string(code.category.machineCategory),
        "exitCode": .integer(Int64(code.exitCode)),
        "controlRequestRetryable": .bool(code.isControlRequestRetryable),
        "attentionRequired": .bool(code.requiresAttention),
      ])
    }
    return .object([
      "schemaVersion": .string(CLIErrorRegistryVersion.current),
      "bundleVersion": .string(CLIProductVersion.machineContract),
      "cliVersion": .string(CLIProductVersion.product),
      "exitCategories": .array(categories),
      "codes": .array(codes),
    ])
  }

  static func appRegistryDocument() -> JSONValue {
    let capabilities: [JSONValue] = AppProductCapabilityRegistry.capabilities.map { capability in
      .object([
        "id": .string(capability.id),
        "surface": .string(capability.surface),
        "title": .string(capability.title),
        "owner": .string(capability.owner),
        "classification": .string(capability.classification.rawValue),
        "cliEquivalent": .array(capability.cliEquivalent.map(JSONValue.string)),
      ])
    }
    return .object([
      "schemaVersion": .string(AppProductCapabilityRegistry.schemaVersion),
      "bundleVersion": .string(CLIProductVersion.machineContract),
      "cliVersion": .string(CLIProductVersion.product),
      "classificationVocabulary": .array(
        ProductCoverageClassification.allCases.map { .string($0.rawValue) }),
      "capabilities": .array(capabilities),
    ])
  }

