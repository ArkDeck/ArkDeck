/// A result or a terminal frame: `result` when `ok`, `error` otherwise,
/// never both.
fn result_or_error() -> Value {
    json!([
        {
            "properties": {"ok": {"const": true}},
            "required": ["result"],
            "not": {"required": ["error"]},
        },
        {
            "properties": {"ok": {"const": false}},
            "required": ["error"],
            "not": {"required": ["result"]},
        },
    ])
}

/// Swift `Schemas.result`.
fn result_schema() -> Value {
    let mut fields = header(
        RESULT_SCHEMA_VERSION,
        "The single result document a machine-mode invocation writes to stdout (§8.1, §8.2).",
    );
    fields.insert("type".into(), json!("object"));
    fields.insert(
        "required".into(),
        json!(["schemaVersion", "command", "ok", "meta"]),
    );
    fields.insert(
        "properties".into(),
        json!({
            "schemaVersion": {"const": RESULT_SCHEMA_VERSION},
            "command": {"type": "string", "pattern": COMMAND_PATTERN},
            "ok": {"type": "boolean"},
            "result": {},
            "error": {"$ref": "#/$defs/error"},
            "meta": {"$ref": "#/$defs/meta"},
        }),
    );
    fields.insert("additionalProperties".into(), json!(false));
    fields.insert("oneOf".into(), result_or_error());
    fields.insert(
        "$defs".into(),
        json!({
            "error": error_object(),
            "lifecycle": lifecycle_object(),
            "meta": {
                "type": "object",
                "required": ["controlRequestId", "cliVersion"],
                "properties": {
                    "controlRequestId": {"type": "string", "pattern": CONTROL_REQUEST_ID_PATTERN},
                    "cliVersion": {"type": "string"},
                    "controlProtocolVersion": {"const": PROTOCOL_VERSION},
                    "lifecycle": {"$ref": "#/$defs/lifecycle"},
                },
                "additionalProperties": false,
            },
            "errorRegistryVersion": {"const": crate::error_registry::VERSION},
        }),
    );
    Value::Object(fields)
}

/// Swift `Schemas.event`: a Runtime event line, or the one terminal frame.
fn event_schema() -> Value {
    let mut fields = header(
        EVENT_SCHEMA_VERSION,
        "One JSONL line of a streaming invocation: a Runtime event or the single terminal frame (§8.3).",
    );
    let mut common = Map::new();
    common.insert(
        "schemaVersion".into(),
        json!({"const": EVENT_SCHEMA_VERSION}),
    );
    common.insert("sequence".into(), json!({"type": "integer", "minimum": 1}));
    common.insert("type".into(), json!({"type": "string", "minLength": 1}));
    common.insert(
        "command".into(),
        json!({"type": "string", "pattern": COMMAND_PATTERN}),
    );
    common.insert(
        "controlRequestId".into(),
        json!({"type": "string", "pattern": CONTROL_REQUEST_ID_PATTERN}),
    );
    let mut terminal = common.clone();
    terminal.insert("type".into(), json!({"const": "terminal"}));
    terminal.insert("ok".into(), json!({"type": "boolean"}));
    terminal.insert(
        "exitCode".into(),
        json!({"type": "integer", "minimum": 0, "maximum": 255}),
    );
    terminal.insert("lastCursor".into(), json!({"type": ["string", "null"]}));
    terminal.insert("result".into(), json!({}));
    terminal.insert("error".into(), json!({"$ref": "#/$defs/error"}));
    let mut event = common;
    if let Value::Object(item) = &event_item()["properties"] {
        event.extend(item.clone());
    }
    fields.insert("type".into(), json!("object"));
    fields.insert(
        "required".into(),
        json!([
            "schemaVersion",
            "sequence",
            "type",
            "command",
            "controlRequestId"
        ]),
    );
    fields.insert(
        "oneOf".into(),
        json!([
            {"$ref": "#/$defs/terminalFrame"},
            {"$ref": "#/$defs/runtimeEventFrame"},
        ]),
    );
    fields.insert(
        "$defs".into(),
        json!({
            "error": error_object(),
            "terminalFrame": {
                "type": "object",
                "required": [
                    "schemaVersion", "sequence", "type", "command", "controlRequestId", "ok",
                    "exitCode", "lastCursor",
                ],
                "properties": terminal,
                "additionalProperties": false,
                "oneOf": result_or_error(),
            },
            "runtimeEventFrame": {
                "type": "object",
                "required": [
                    "schemaVersion", "sequence", "type", "command", "controlRequestId", "eventId",
                    "streamPosition", "cursor",
                ],
                "properties": event,
                "not": {"properties": {"type": {"const": "terminal"}}},
            },
        }),
    );
    Value::Object(fields)
}

/// Swift `Schemas.controlPlane`: the frames the CLI exchanges with the
/// Runtime, and the closed method set it may name, each pointing at its
/// typed schema. It is built from the compiled contract, so it follows the
/// contract inputs.
fn control_plane_schema() -> Value {
    let mut fields = header(
        CONTROL_PLANE_SCHEMA_VERSION,
        "The local control-plane request and response frames the CLI exchanges with the Runtime, and the closed method set it may name.",
    );
    let mut methods: Vec<&str> = METHODS.to_vec();
    methods.sort_unstable();
    let table: Vec<Value> = methods
        .iter()
        .map(|method| {
            json!({
                "method": method,
                "published": true,
                "schema": format!("{CONTROL_METHOD_SCHEMA_DIRECTORY}/{method}.json"),
            })
        })
        .collect();
    fields.insert(
        "oneOf".into(),
        json!([{"$ref": "#/$defs/request"}, {"$ref": "#/$defs/response"}]),
    );
    fields.insert(
        "x-arkdeck-currentProtocolVersion".into(),
        json!(PROTOCOL_VERSION),
    );
    fields.insert(
        "x-arkdeck-contractIdentity".into(),
        json!(CONTRACT_IDENTITY),
    );
    fields.insert(
        "x-arkdeck-methodSchemaDirectory".into(),
        json!(CONTROL_METHOD_SCHEMA_DIRECTORY),
    );
    fields.insert("x-arkdeck-methods".into(), json!(table));
    fields.insert(
        "$defs".into(),
        json!({
            "request": {
                "type": "object",
                "required": ["protocolVersion", "contractIdentity", "id", "method"],
                "properties": {
                    "protocolVersion": {"const": PROTOCOL_VERSION},
                    "contractIdentity": {"const": CONTRACT_IDENTITY},
                    "id": {"type": "string", "minLength": 1},
                    "method": {"enum": methods},
                    "params": {"type": "object"},
                },
                "additionalProperties": false,
            },
            "response": {
                "type": "object",
                "required": ["id", "ok"],
                "properties": {
                    "id": {"type": "string", "minLength": 1},
                    "ok": {"type": "boolean"},
                    "result": {},
                    "error": {"$ref": "#/$defs/wireError"},
                },
                "additionalProperties": false,
                "oneOf": result_or_error(),
            },
            "wireError": {
                "type": "object",
                "required": ["code", "message"],
                "properties": {
                    "code": {"type": "string", "minLength": 1},
                    "message": {"type": "string"},
                    "details": {"type": "object"},
                },
                "additionalProperties": false,
            },
        }),
    );
    Value::Object(fields)
}

