/// The fixtures this CLI owns next to the contract tests
/// (`Fixtures/CLI/`), sorted by path as Swift writes them.
pub fn fixture_products() -> Vec<Product> {
    let mut products: Vec<Product> = next_actions()
        .into_iter()
        .map(|(kind, document)| Product::json(&format!("next-action/{kind}.json"), &document))
        .collect();
    products.push(Product::json("next-action/null.json", &Value::Null));
    products.push(Product::json("page/snapshot.json", &snapshot_page()));
    products.push(Product::json(
        "page/event-stream.json",
        &event_stream_page(),
    ));
    products.extend(envelope_products());
    products.sort_by(|left, right| left.relative_path.cmp(&right.relative_path));
    products
}

// MARK: Rendering

/// Swift `ContractJSON.document`: pretty JSON with keys in
/// `arkdeck.cli.canonical-json/1` order (UTF-16 code units), two-space
/// indentation, scalars as the canonical encoder writes them, empty
/// containers inline, and one trailing LF.
pub fn json_document(value: &Value) -> Vec<u8> {
    let mut out = String::new();
    render(value, 0, &mut out);
    out.push('\n');
    out.into_bytes()
}

/// A scalar as the canonical encoder writes it; Swift writes `null` for one
/// the encoder refuses.
fn scalar(value: &Value) -> String {
    canonical_json(value)
        .ok()
        .and_then(|bytes| String::from_utf8(bytes).ok())
        .unwrap_or_else(|| "null".into())
}

/// Keys in UTF-16 code-unit order.
fn sorted_keys(fields: &Map<String, Value>) -> Vec<&String> {
    let mut keys: Vec<&String> = fields.keys().collect();
    keys.sort_by(|left, right| left.encode_utf16().cmp(right.encode_utf16()));
    keys
}

fn render(value: &Value, indent: usize, out: &mut String) {
    let pad = "  ".repeat(indent);
    match value {
        Value::Object(fields) if fields.is_empty() => out.push_str("{}"),
        Value::Object(fields) => {
            out.push_str("{\n");
            let keys = sorted_keys(fields);
            for (offset, key) in keys.iter().enumerate() {
                out.push_str(&pad);
                out.push_str("  ");
                out.push_str(&scalar(&Value::String((*key).clone())));
                out.push_str(": ");
                render(&fields[*key], indent + 1, out);
                out.push_str(if offset == keys.len() - 1 {
                    "\n"
                } else {
                    ",\n"
                });
            }
            out.push_str(&pad);
            out.push('}');
        }
        Value::Array(items) if items.is_empty() => out.push_str("[]"),
        Value::Array(items) => {
            out.push_str("[\n");
            for (offset, item) in items.iter().enumerate() {
                out.push_str(&pad);
                out.push_str("  ");
                render(item, indent + 1, out);
                out.push_str(if offset == items.len() - 1 {
                    "\n"
                } else {
                    ",\n"
                });
            }
            out.push_str(&pad);
            out.push(']');
        }
        other => out.push_str(&scalar(other)),
    }
}

/// Swift `ContractYAML.document`: the YAML subset the bundle uses, block
/// mappings and sequences whose every scalar, keys included, is a JSON scalar
/// from the canonical encoder, after the generated notice.
pub fn yaml_document(value: &Value) -> Vec<u8> {
    let mut out = format!("# {GENERATED_NOTICE}\n");
    out.push_str(&yaml_lines(value).join("\n"));
    out.push('\n');
    out.into_bytes()
}

/// A value written on its key's own line: a scalar or an empty container.
fn yaml_inline(value: &Value) -> bool {
    match value {
        Value::Object(fields) => fields.is_empty(),
        Value::Array(items) => items.is_empty(),
        _ => true,
    }
}

fn yaml_scalar(value: &Value) -> String {
    match value {
        Value::Object(_) => "{}".into(),
        Value::Array(_) => "[]".into(),
        other => scalar(other),
    }
}

fn yaml_lines(value: &Value) -> Vec<String> {
    match value {
        Value::Object(fields) if fields.is_empty() => vec!["{}".into()],
        Value::Object(fields) => {
            let mut out = Vec::new();
            for key in sorted_keys(fields) {
                let child = &fields[key];
                let rendered = scalar(&Value::String(key.clone()));
                if yaml_inline(child) {
                    out.push(format!("{rendered}: {}", yaml_scalar(child)));
                } else {
                    out.push(format!("{rendered}:"));
                    out.extend(
                        yaml_lines(child)
                            .into_iter()
                            .map(|line| format!("  {line}")),
                    );
                }
            }
            out
        }
        Value::Array(items) if items.is_empty() => vec!["[]".into()],
        Value::Array(items) => {
            let mut out = Vec::new();
            for item in items {
                if yaml_inline(item) {
                    out.push(format!("- {}", yaml_scalar(item)));
                } else {
                    let nested = yaml_lines(item);
                    out.push(format!("- {}", nested[0]));
                    out.extend(nested[1..].iter().map(|line| format!("  {line}")));
                }
            }
            out
        }
        other => vec![scalar(other)],
    }
}

// MARK: Registries

/// Swift `commandRegistryDocument`: the registry's projection, as this CLI
/// carries it (`command_registry.json`), with the bundle's versions and the
/// Catalog's digest.
fn command_registry_document() -> Value {
    let registry = crate::command_registry::projection();
    json!({
        "schemaVersion": registry["commandRegistrySchemaVersion"],
        "bundleVersion": BUNDLE_VERSION,
        "cliVersion": crate::CLI_VERSION,
        "catalogDigest": CATALOG_DIGEST,
        "commands": registry["commands"],
    })
}

/// Swift `errorRegistryDocument`: every exit category with its codes, and
/// every code with its category, exit status, retryability and attention.
fn error_registry_document() -> Value {
    use crate::error_registry::{
        CODES, ExitCategory, VERSION, control_request_retryable, requires_attention,
    };
    let categories: Vec<Value> = ExitCategory::ALL
        .iter()
        .map(|category| {
            json!({
                "category": category.machine_name(),
                "exitCode": category.exit_code(),
                "codes": CODES
                    .iter()
                    .filter(|(_, owner)| owner == category)
                    .map(|(code, _)| *code)
                    .collect::<Vec<_>>(),
            })
        })
        .collect();
    let codes: Vec<Value> = CODES
        .iter()
        .map(|(code, category)| {
            json!({
                "code": code,
                "category": category.machine_name(),
                "exitCode": category.exit_code(),
                "controlRequestRetryable": control_request_retryable(code),
                "attentionRequired": requires_attention(code),
            })
        })
        .collect();
    json!({
        "schemaVersion": VERSION,
        "bundleVersion": BUNDLE_VERSION,
        "cliVersion": crate::CLI_VERSION,
        "exitCategories": categories,
        "codes": codes,
    })
}

/// Swift `canonicalVectorsSchemaVersion` and `CLICanonicalJSON.version`.
const CANONICAL_VECTORS_SCHEMA_VERSION: &str = "arkdeck.cli.canonical-json-vectors/1";
const CANONICAL_JSON_VERSION: &str = "arkdeck.cli.canonical-json/1";

/// Swift `canonicalVectorInputs`: values a port must encode as this build
/// does.
fn canonical_vectors() -> Vec<(&'static str, Value)> {
    vec![
        ("emptyObject", json!({})),
        ("emptyArray", json!([])),
        ("scalars", json!([null, true, false, 0, ""])),
        (
            "keyOrderIsUtf16CodeUnit",
            json!({"b": 1, "a": 2, "aa": 3, "B": 0}),
        ),
        (
            "nonAsciiKeyOrder",
            json!({"z": 1, "\u{E9}": 2, "\u{1F600}": 3, "Z": 4}),
        ),
        (
            "stringEscapes",
            json!(
                "quote\" backslash\\ newline\n tab\t control\u{1} slash/ euro\u{20AC} emoji\u{1F600}"
            ),
        ),
        ("integers", json!([-1, 1, 9_007_199_254_740_991_i64])),
        ("unsignedInteger", json!(9_007_199_254_740_991_u64)),
        ("numbers", json!([0.5, 1.0, -0.0, 1e21, 123_456_789.125])),
        (
            "nested",
            json!({"list": [{}, [], {"k": [null]}], "text": "x"}),
        ),
    ]
}

/// Swift `canonicalRejectionInputs`, each with the refusal the published
/// bundle records (Swift's description of its encoder's error). This build
/// refuses the two integers too (`canonical_rejections_are_this_builds`); a
/// non-finite number cannot be held in a `serde_json::Value` at all, so this
/// build never accepts one either.
pub const CANONICAL_REJECTIONS: [(&str, &str); 5] = [
    ("positiveInfinity", "nonFiniteNumber"),
    ("negativeInfinity", "nonFiniteNumber"),
    ("nan", "nonFiniteNumber"),
    (
        "integerBeyondExactRange",
        "integerBeyondExactRange(\"9223372036854775807\")",
    ),
    (
        "unsignedIntegerBeyondExactRange",
        "integerBeyondExactRange(\"18446744073709551615\")",
    ),
];

/// Swift `canonicalVectorsDocument`: each vector with the canonical text this
/// build's encoder gives it, and the refusals.
fn canonical_vectors_document() -> Value {
    let vectors: Vec<Value> = canonical_vectors()
        .into_iter()
        .map(|(name, value)| {
            let canonical = String::from_utf8(
                canonical_json(&value).expect("every canonical vector is encodable"),
            )
            .expect("canonical JSON is UTF-8");
            json!({"name": name, "value": value, "canonical": canonical})
        })
        .collect();
    let rejections: Vec<Value> = CANONICAL_REJECTIONS
        .iter()
        .map(|(name, reason)| json!({"name": name, "reason": reason}))
        .collect();
    json!({
        "schemaVersion": CANONICAL_VECTORS_SCHEMA_VERSION,
        "canonicalJsonVersion": CANONICAL_JSON_VERSION,
        "bundleVersion": BUNDLE_VERSION,
        "cliVersion": crate::CLI_VERSION,
        "vectors": vectors,
        "rejections": rejections,
    })
}

// MARK: JSON Schemas

/// Swift `Schemas.header`.
fn header(title: &str, description: &str) -> Map<String, Value> {
    let mut fields = Map::new();
    fields.insert("$schema".into(), json!(DRAFT));
    fields.insert("$comment".into(), json!(GENERATED_NOTICE));
    fields.insert("title".into(), json!(title));
    fields.insert("description".into(), json!(description));
    fields.insert("x-arkdeck-bundleVersion".into(), json!(BUNDLE_VERSION));
    fields.insert("x-arkdeck-cliVersion".into(), json!(crate::CLI_VERSION));
    fields
}

/// Swift `Schemas.errorObject`: a failure's error, its code one of the
/// registry's.
