/// One generated file: a path relative to its root, and its exact bytes.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Product {
    pub relative_path: String,
    pub bytes: Vec<u8>,
}

impl Product {
    fn json(relative_path: &str, value: &Value) -> Self {
        Self {
            relative_path: relative_path.into(),
            bytes: json_document(value),
        }
    }
}

