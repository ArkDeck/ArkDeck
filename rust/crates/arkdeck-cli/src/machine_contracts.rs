/// Swift `Schemas.page`.
fn page_schema() -> Value {
    let mut fields = header(
        PAGE_SCHEMA_VERSION,
        "The fixed page shape every list and events result uses (§7.3).",
    );
    fields.insert("type".into(), json!("object"));
    fields.insert(
        "required".into(),
        json!([
            "schemaVersion",
            "pageKind",
            "items",
            "order",
            "snapshotRevision",
            "hasMore",
            "nextCursor",
        ]),
    );
    fields.insert(
        "properties".into(),
        json!({
            "schemaVersion": {"const": PAGE_SCHEMA_VERSION},
            "pageKind": {"enum": ["snapshot", "eventStream"]},
            "items": {"type": "array"},
            "order": {"type": "string", "minLength": 1},
            "snapshotRevision": {"type": "string"},
            "hasMore": {"type": "boolean"},
            "nextCursor": {"type": ["string", "null"]},
        }),
    );
    fields.insert("additionalProperties".into(), json!(false));
    fields.insert(
        "allOf".into(),
        json!([
            {
                "if": {"properties": {"pageKind": {"const": "eventStream"}}},
                "then": {"properties": {
                    "order": {"const": "streamPositionAsc"},
                    "nextCursor": {"type": "string", "minLength": 1},
                    "items": {"items": {"$ref": "#/$defs/eventItem"}},
                }},
            },
            {
                "if": {"properties": {
                    "pageKind": {"const": "snapshot"},
                    "hasMore": {"const": false},
                }},
                "then": {"properties": {"nextCursor": {"type": "null"}}},
            },
            {
                "if": {"properties": {"hasMore": {"const": true}}},
                "then": {"properties": {"nextCursor": {"type": "string", "minLength": 1}}},
            },
        ]),
    );
    fields.insert("$defs".into(), json!({"eventItem": event_item()}));
    Value::Object(fields)
}

