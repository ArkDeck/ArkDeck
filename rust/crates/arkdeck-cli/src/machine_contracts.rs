/// Swift `Schemas.branch`: one closed branch of the §7.3 union.
fn branch(
    kind: &str,
    owner_kinds: &[&str],
    resource_kinds: &[&str],
    reason_codes: Option<&[&str]>,
    extra: Value,
    required: &[&str],
    resource_mirrors_owner: bool,
) -> Value {
    let mut properties = Map::new();
    properties.insert("kind".into(), json!({"const": kind}));
    properties.insert("owner".into(), owner_object(owner_kinds));
    properties.insert("resource".into(), owner_object(resource_kinds));
    properties.insert(
        "reasonCode".into(),
        match reason_codes {
            Some(codes) => json!({"enum": codes}),
            None => json!({"type": "string", "minLength": 1}),
        },
    );
    if let Value::Object(extra) = extra {
        properties.extend(extra);
    }
    let mut all_required = vec!["kind", "owner", "resource", "reasonCode"];
    all_required.extend_from_slice(required);
    let mut fields = Map::new();
    fields.insert("type".into(), json!("object"));
    fields.insert("required".into(), json!(all_required));
    fields.insert("properties".into(), Value::Object(properties));
    fields.insert("additionalProperties".into(), json!(false));
    if resource_mirrors_owner {
        fields.insert(
            "allOf".into(),
            owner_kinds
                .iter()
                .map(|owner| {
                    json!({
                        "if": {"properties": {"owner": {"properties": {"kind": {"const": owner}}}}},
                        "then": {"properties": {"resource": {"properties": {"kind": {"const": owner}}}}},
                    })
                })
                .collect(),
        );
    }
    Value::Object(fields)
}

