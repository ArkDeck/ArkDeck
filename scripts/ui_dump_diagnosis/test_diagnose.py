def _sha256_hex(data):
    return hashlib.sha256(data).hexdigest()


def _collect_import_roots(tree):
    plain_roots = set()
    from_roots = set()
    from_nodes = 0
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                plain_roots.add(alias.name.split(".")[0])
        elif isinstance(node, ast.ImportFrom):
            from_nodes += 1
            if node.module:
                from_roots.add(node.module.split(".")[0])
    return plain_roots, from_roots, from_nodes


def _collect_attributes_of(tree, base_name):
    attributes = set()
    for node in ast.walk(tree):
        if (
            isinstance(node, ast.Attribute)
            and isinstance(node.value, ast.Name)
            and node.value.id == base_name
        ):
            attributes.add(node.attr)
    return attributes


def _collect_os_path_attributes(tree):
    attributes = set()
    for node in ast.walk(tree):
        if (
            isinstance(node, ast.Attribute)
            and isinstance(node.value, ast.Attribute)
            and isinstance(node.value.value, ast.Name)
            and node.value.value.id == "os"
            and node.value.attr == "path"
        ):
            attributes.add(node.attr)
    return attributes


def _collect_called_names(tree):
    names = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name):
            names.add(node.func.id)
    return names


class DiagnoseContractTest(unittest.TestCase):
    maxDiff = None

    def setUp(self):
        candidate = tempfile.mkdtemp(prefix="ud-diag-")
        if os.path.realpath(candidate).startswith(REPO_ROOT + os.sep):
            shutil.rmtree(candidate, ignore_errors=True)
            candidate = tempfile.mkdtemp(prefix="ud-diag-", dir="/tmp")
        self.tmp = candidate
        self.addCleanup(shutil.rmtree, candidate, ignore_errors=True)

    # ---- helpers -------------------------------------------------------

    def write_fixture(self, name, data):
        path = os.path.join(self.tmp, name)
        with open(path, "wb") as handle:
            handle.write(data)
        return path

    def run_cli(self, argv):
        stdout = io.StringIO()
        stderr = io.StringIO()
        with contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(
            stderr
        ):
            try:
                code = diagnose.main(argv)
            except SystemExit as exc:
                code = exc.code
        return code, stdout.getvalue(), stderr.getvalue()

    def run_cli_on_bytes(self, data, name="fixture.bin"):
        path = self.write_fixture(name, data)
        return self.run_cli(
            [
                "--input",
                path,
                "--expected-input-sha256",
                _sha256_hex(data),
                "--expected-length",
                str(len(data)),
            ]
        )

    def diagnose_file(self, data, name="fixture.bin"):
        code, stdout, stderr = self.run_cli_on_bytes(data, name=name)
        self.assertEqual(code, 0)
        self.assertEqual(stderr, "")
        self.assertTrue(stdout.endswith("\n"))
        self.assertEqual(stdout.count("\n"), 1)
        report = json.loads(stdout)
        expected_decodable = True
        try:
            data.decode("utf-8")
        except UnicodeDecodeError:
            expected_decodable = False
        self.assertEqual(
            report["utf8Structure"]["decodable"], expected_decodable
        )
        return report

    def assert_stable_error(self, code, stdout, stderr, name):
        self.assertEqual(code, diagnose.ERROR_CODES[name])
        self.assertEqual(stdout, "")
        self.assertEqual(stderr, f"diagnose: {name}\n")

    def utf8_runs(self, report):
        return [
            (entry["offset"], entry["length"], entry["class"])
            for entry in report["utf8Structure"]["runs"]
        ]

    def policy_runs(self, report):
        return [
            (entry["offset"], entry["length"], entry["class"])
            for entry in report["codepointPolicy"]["runs"]
        ]

    def assert_clean_policy(self, report, nfc=True):
        policy = report["codepointPolicy"]
        self.assertTrue(policy["evaluated"])
        self.assertEqual(policy["nfc"], nfc)
        self.assertEqual(policy["violationCount"], 0)
        self.assertIsNone(policy["firstViolationByteOffset"])
        self.assertIsNone(policy["lastViolationByteOffset"])
        self.assertEqual(policy["runs"], [])

    def assert_equivalent(self, report, name, code):
        self.assertEqual(
            report["redactorEquivalent"], {"errorName": name, "errorCode": code}
        )

    def tampered_run(self, data, tamper):
        """Run the real CLI path with the built report tampered post-build."""
        original = diagnose.diagnose_bytes

        def wrapper(*args, **kwargs):
            report = original(*args, **kwargs)
            tamper(report)
            return report

        diagnose.diagnose_bytes = wrapper
        try:
            return self.run_cli_on_bytes(data, name="tampered.bin")
        finally:
            diagnose.diagnose_bytes = original

