    def test_policy_19_tab_and_other_c0_with_line_ending_exemption(self):
        data = b"a\tb\x01c\r\nd\n"
        report = self.diagnose_file(data)
        self.assertEqual(
            self.policy_runs(report),
            [(1, 1, "CONTROL_C0"), (3, 1, "CONTROL_C0")],
        )
        policy = report["codepointPolicy"]
        # Exactly two violations: the LF/CR bytes in the same file are
        # exempt, mirroring allow_line_endings=True in the redactor.
        self.assertEqual(policy["violationCount"], 2)
        self.assertEqual(policy["classCounts"]["CONTROL_C0"], 2)
        histogram = report["byteHistogram"]
        self.assertEqual(histogram["tab"], 1)
        self.assertEqual(histogram["otherC0"], 1)
        self.assertEqual(histogram["cr"], 1)
        self.assertEqual(histogram["lf"], 2)
        self.assert_equivalent(report, "INVALID_UNICODE", 27)
        lone_line_endings = self.diagnose_file(
            b"\n\r\r\n", name="line-endings-only.bin"
        )
        self.assertEqual(
            lone_line_endings["codepointPolicy"]["violationCount"], 0
        )
        self.assert_equivalent(lone_line_endings, "NONE", None)

