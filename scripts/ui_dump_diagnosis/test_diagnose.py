    def _assert_closed_string(self, value):
        self.assertTrue(
            value in EXPECTED_STRING_WHITELIST
            or (
                len(value) == 64
                and all(ch in "0123456789abcdef" for ch in value)
            ),
            f"free-form string escaped the value law: {value!r}",
        )

    def _walk_independent_value_law(self, value):
        if isinstance(value, dict):
            for key, item in value.items():
                self.assertIsInstance(key, str)
                self._walk_independent_value_law(item)
        elif isinstance(value, list):
            for item in value:
                self._walk_independent_value_law(item)
        elif isinstance(value, str):
            self._assert_closed_string(value)
        else:
            self.assertTrue(
                value is None or type(value) is bool or type(value) is int,
                f"non-closed value type: {value!r}",
            )

