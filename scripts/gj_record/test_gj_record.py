class CaptureTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.root = Path(self.temporary.name)
        self.cli = self.root / "arkdeck.exe"
        self.cli.write_bytes(b"image")
        self.repository = self.root / "repo"
        self.repository.mkdir()

    def tearDown(self):
        self.temporary.cleanup()

    def runner(self, stdout: bytes, code: int):
        calls = []

        def run(argv, **kwargs):
            calls.append((argv, kwargs))
            return subprocess.CompletedProcess(argv, code, stdout=stdout)

        return run, calls

    def test_capture_keeps_stdout_exit_code_and_order(self):
        envelope = json.dumps({"schemaVersion": "arkdeck.cli.result/1", "command": "agent.run", "ok": False}).encode()
        run, calls = self.runner(envelope, 75)
        out = self.root / "out"
        for step in ("gj1.har", "gj1.har-status"):
            entry = capture.capture(out, step, [str(self.cli), "agent", "run", "--output", "json"],
                                    repository=self.repository, quiet=True, runner=run)
        self.assertEqual(entry["sequence"], 2)
        self.assertEqual(entry["exitCode"], 75)
        self.assertEqual(entry["cliExecutableSHA256"], sha(b"image"))
        self.assertEqual((out / entry["stdoutFile"]).read_bytes(), envelope)
        self.assertEqual([e["step"] for e in capture.read_journal(out)], ["gj1.har", "gj1.har-status"])
        self.assertEqual(calls[0][1]["stdin"], subprocess.DEVNULL)
        self.assertIsInstance(calls[0][0], list)

    def test_capture_refuses_output_inside_the_repository_and_human_output(self):
        run, calls = self.runner(b"{}", 0)
        with self.assertRaisesRegex(capture.CaptureError, "inside the repository"):
            capture.capture(self.repository / "out", "s", [str(self.cli), "doctor", "--output", "json"],
                            repository=self.repository, runner=run)
        with self.assertRaisesRegex(capture.CaptureError, "--output json"):
            capture.capture(self.root / "out", "s", [str(self.cli), "doctor"], repository=self.repository, runner=run)
        self.assertEqual(calls, [])

    def test_capture_hashes_the_daemon_image_a_windows_status_names(self):
        daemon = self.root / "arkdeck-agentd.exe"
        daemon.write_bytes(b"daemon")
        envelope = json.dumps({"schemaVersion": "arkdeck.cli.result/1", "command": "runtime.service.status", "ok": True,
                               "result": {"daemonService": {"daemonPath": str(daemon)}}}).encode()
        run, _ = self.runner(envelope, 0)
        entry = capture.capture(self.root / "out", "facts.status",
                                [str(self.cli), "runtime", "service", "status", "--output", "json"],
                                repository=self.repository, quiet=True, runner=run)
        self.assertEqual(entry["daemonImageSHA256"], sha(b"daemon"))


