    def test_an_operation_list_from_another_catalog_is_refused(self):
        self.journal.facts(operations=OPERATIONS[:-1])
        self.refused("canonical operation set")

    def test_a_record_carrying_a_connect_key_is_refused(self):
        with self.assertRaisesRegex(redact.RedactionError, "identifying literal"):
            redact.check(f'{{"notes": "{CONNECT_KEY}"}}', {CONNECT_KEY})
        for text in ('"C:\\\\x"', '"/Users/me"', '"192.168.0.2:8710"', '"%LOCALAPPDATA%"'):
            with self.assertRaises(redact.RedactionError, msg=text):
                redact.check(text, set())


